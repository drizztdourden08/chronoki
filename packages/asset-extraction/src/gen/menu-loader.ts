/* @layer shared-asset-extraction @kind logic */
import type { ImportContext } from '../pipeline/import-context.type';
import { cgWord } from './ctgen/cg-word';
import { x5 } from './ctgen/x5';
import { hx } from './ctgen/hx';
import { crlf } from './ctgen/crlf';
import { iconBlock, numeralBlock, toneBlock } from './menu-loader-art';
import type { LoaderCapture } from './menu-loader-capture';
import { captureLoader } from './menu-loader-capture';
import { stringBlock } from './menu-loader-strings';

const HEADER =
  '// menu_loader.h - the LOAD screen (menu mode 0, screen 0x0E, ROM handler C2/E60B;\n' +
  "// builder C2/E7C3).  GENERATED by tools/gen_menuloader.py from the oracle's own VRAM,\n" +
  '// CGRAM and HDMA tables on a boot whose cart carries saves/ct_real_save.srm -- a game the\n' +
  '// ROM itself saved.  Same chrome TILE SET as every other menu screen (the generator\n' +
  '// refuses to emit if a tile outside 0x300..0x3EF appears) but its OWN CGRAM: the slot\n' +
  "// buttons carry tilemap palettes 1/2/3, and those rows differ from the X-menu's.\n" +
  '//\n' +
  '// ⭐ AND ITS OWN PER-SCANLINE SCROLL.  This screen is NOT a flat tilemap: BG2VOFS ($2110)\n' +
  "// is HDMA'd in three bands, so the same three button blocks in the map are shown FOUR\n" +
  '// times -- band 1 puts the SECOND screen\'s rows 1-4 up as the "New Game" bar, band 2 puts\n' +
  '// first-screen rows 2-5 / 6-9 / 10-13 underneath it as the three save slots, and band 3\n' +
  '// puts rows 16-25 (the two bottom windows) below those.  Replaying the plane flat gives\n' +
  '// three bars and no New Game row; see CtMenuChromeLoader.\n' +
  '#ifndef CT_MENU_LOADER_H\n#define CT_MENU_LOADER_H\n#include <stdint.h>\n\n' +
  '#define CT_MENU_LOADER_TMH 64\n' +
  'static const uint16_t ctMenuChromeLoaderTM[32*CT_MENU_LOADER_TMH] = {\n';

const tilemapBlock = (cells: number[]): string => {
  let s = '';
  for (let r = 0; r < 64; r += 1) {
    s += `  ${Array.from({ length: 32 }, (_, c) => `0x${hx(cells[r * 32 + c] as number, 4)},`).join(' ')}\n`;
  }
  return `${s}};\n\n`;
};

const bandBlock = (bands: [number, number][]): string => {
  let s =
    "// The BG2VOFS ($2110) HDMA bands, read out of the oracle's own table at $7E:9080:\n" +
    `//   ${bands.map(([c, v]) => `${c} lines @ 0x${hx(v, 4)}`).join(' | ')}\n` +
    '// The map line a scanline shows is (y + vofs) & 0x1FF over the 32x64 map above.\n' +
    `#define CT_MENU_LOADER_NBAND ${bands.length}\n` +
    'static const struct { short y0, y1; unsigned short vofs; }\n' +
    'ctMenuLoaderBand[CT_MENU_LOADER_NBAND] = {\n';
  let y0 = 0;
  for (const [c, v] of bands) {
    s += `  { ${String(y0).padStart(3)}, ${String(y0 + c - 1).padStart(3)}, 0x${hx(v, 4)} },\n`;
    y0 += c;
  }
  return `${s}};\n\n`;
};

const palBlock = (cg: Uint8Array): string => {
  let s = 'static const uint8_t ctMenuChromeLoaderPal[8][16][3] = {\n';
  for (let row = 0; row < 8; row += 1) {
    const cells = Array.from({ length: 16 }, (_, i) => {
      const w = cgWord(cg, row * 16 + i);
      return `{${x5(w & 31)},${x5((w >> 5) & 31)},${x5((w >> 10) & 31)}}`;
    });
    s += `  {${cells.join(',')}},\n`;
  }
  return `${s}};\n\n`;
};

const render = (c: LoaderCapture, rom: Uint8Array): string =>
  HEADER +
  tilemapBlock(c.cells) +
  bandBlock(c.bands) +
  palBlock(c.cg) +
  iconBlock(rom) +
  toneBlock(c.cg) +
  numeralBlock(c.vram, c.cg) +
  stringBlock(rom);

/** tools/gen/menu_loader.py: everything the Load screen (menu mode 0, screen 0x0E) is drawn from (battery of recipe name_saved). */
const genMenuLoader = async (ctx: ImportContext): Promise<string> => crlf(render(await captureLoader(ctx), ctx.rom));

export { genMenuLoader };

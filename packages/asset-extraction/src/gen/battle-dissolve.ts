/* @layer shared-asset-extraction @kind logic */
import type { ImportContext } from '../pipeline/import-context.type';
import { peekOracle, recipeState } from '../oracle/peek-access';
import { measure } from './battle-dissolve/dissolve-measure';
import { verifyBad } from './battle-dissolve/verify-bad';
import type { Seq } from './battle-dissolve/dissolve-measure.type';
import { sprite } from './battle-dissolve/dissolve-sprite';
import type { GenFiles } from './oracle-gen-stage.type';
import { dec } from './shared/py-format';
import { NAV, WINDOW_LO, WINDOW_HI } from './battle-dissolve.constants';

const emit = (dither: number[][]): string => {
  const L: string[] = [
    '/* battle_dissolve.h -- enemy-death DISSOLVE (GENERATED by',
    ' * tools/gen/battle_dissolve.py; derived in disasm/notes/battle_dissolve.md T2).',
    ' * Mechanism: on enemy death, its OBJ sprites move to pal4 (CF/FE20), then an 8x8',
    ' * ordered-dither matrix clears the OBJ pixels ~20/frame over 32 frames, then the',
    ' * OAM sprites are removed. Pixel present iff ctBattleDissolveDither[y%8][x%8] >= step,',
    ' * step = curFrame - dissolveStart (0..31). Byte-exact vs oracle (see --verify). */',
    '#ifndef CT_BATTLE_DISSOLVE_H',
    '#define CT_BATTLE_DISSOLVE_H',
    '',
    '#define CT_DISSOLVE_STEPS      32   /* dither levels; pixel clears at step==dither+1 */',
    "/* The timing is not here either: CD/0043's own waits (battle.c battleDeathRoutineStart, battleAdvanceDissolves). */",
    '#define CT_DISSOLVE_RATE_PX    20   /* px cleared per frame (emergent from the matrix) */',
    "/* The recolor is not here: the corpse draws with the live OBJ palette its $993C names -- CF/FE20's copy into",
    " * palette 4 and CD/00A5's red fade record (battle_death_dissolve_gate.md PART 5). */",
    '',
    '/* clear-STEP per sprite-local pixel (x%8,y%8): present iff this >= step. */',
    'static const unsigned char ctBattleDissolveDither[8][8] = {',
    ...dither.map((row) => `  {${row.map((v) => dec(v, 2)).join(', ')}},`),
    '};',
    '',
    '#endif /* CT_BATTLE_DISSOLVE_H */',
  ];
  return `${L.join('\n')}\n`;
};

const genBattleDissolve = async (ctx: ImportContext): Promise<GenFiles> => {
  const state = await recipeState(ctx, 'forest_battle_3hetake');
  const frames: number[] = [];
  for (let n = WINDOW_LO; n < WINDOW_HI; n += 1) frames.push(n);
  const got = await peekOracle(ctx).peekShots({ state, script: NAV, at: frames });
  const seq: Seq = new Map();
  for (const n of frames) {
    const dump = got.get(n);
    if (!dump) throw new Error(`battle_dissolve: the oracle returned no dump for peek frame ${n}`);
    seq.set(n, sprite(dump.vram));
  }
  const { start, dither } = measure(seq);
  const steps = [...new Set(dither.flat())].sort((a, b) => a - b);
  const { bad, tot } = verifyBad(seq, start, dither);
  if (bad !== 0) {
    throw new Error(
      `battle_dissolve verify: frames ${start}..${WINDOW_HI - 1}, ${tot} px predicted from the start frame + the table, ${bad} differ`,
    );
  }
  if (steps.length !== 32 || steps.some((v, i) => v !== i)) {
    throw new Error('battle_dissolve: the steps are not 0..31 (CT_DISSOLVE_STEPS)');
  }
  return { 'battle_dissolve.h': emit(dither) };
};

export { genBattleDissolve };

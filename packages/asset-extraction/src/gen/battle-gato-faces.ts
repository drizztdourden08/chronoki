import type { ImportContext } from '../pipeline/import-context.type';
import { peekOracle } from '../oracle/peek-access';
import { recipeState } from '../oracle/recipe-state';
import type { PeekDump } from '../oracle/peek.type';
import { hex } from './c-text';
import type { GenFiles } from './oracle-gen-stage';
import { BRACKET_TILE, NTILE, bodyMd5, gatoFoot, sheetRows, tileSheet } from './shared/gato-bake';
import { decodeOam, oamBlob } from './shared/oam-decode';
import type { Sprite } from './shared/oam-decode';
import { dec } from './shared/py-format';

interface Baked {
  name: string;
  facing: number;
  rel: { rx: number; ry: number; tile: number }[];
  tiles: Uint8Array[];
  md5: string;
}

const cellsOf = (sprites: Sprite[]): Sprite[] =>
  sprites.filter((s) => s.y < 210 && s.x > -60 && s.x < 256 && s.pal === 1 && s.tile !== BRACKET_TILE);

const emit = (baked: Baked[]): string => {
  const out: string[] = [];
  const W = (s: string): void => {
    out.push(s);
  };
  W("// GENERATED by tools/gen/battle_gato_faces.py -- do not edit. GATO's directional facing pose bakes\n");
  W('// (disasm/notes/battle_pc_approach_facing.md PART 2): UP/LEFT/RIGHT rep frames from the oracle\n');
  W('// captures (gm_60 up-walk; facing/left, facing/right HOLD-fight walks). DOWN (facing 1) = the\n');
  W("// committed idle bake (battle_anim.h kf6/7), not duplicated here. Cells are RELATIVE TO GATO'S\n");
  W('// LIVE FOOT ($1D0C+6/$1D23+6 at capture; fb-row convention pinned against CT_EXT_GATO). Four\n');
  W('// distinct tile sets -- LEFT/RIGHT are NOT h-flips (2.4); hf=vf=0 throughout. The within-facing\n');
  W('// walk-cycle tile stream is the dossier P4 OPEN boundary (one rep frame per facing).\n');
  W('#ifndef CT_BATTLE_GATO_FACES_H\n#define CT_BATTLE_GATO_FACES_H\n#include <stdint.h>\n\n');
  W('typedef struct { int16_t relX, relY; uint16_t tile; } CtGatoFaceCell;\n');
  W('typedef struct { const char* pose; uint8_t facing; uint8_t cellOff, nCell; } CtGatoFaceKf;\n\n');
  W('static const CtGatoFaceCell ctGatoFaceCell[] = {\n');
  for (const b of baked) {
    W(`  // ${b.name} (facing ${b.facing})\n`);
    for (const c of b.rel) W(`  { ${dec(c.rx, 4)}, ${dec(c.ry, 4)}, 0x${hex(c.tile, 3)} },\n`);
  }
  W('};\n\n');
  W('static const CtGatoFaceKf ctGatoFaceKf[3] = {\n');
  let off = 0;
  for (const b of baked) {
    W(`  { "${b.name}", ${b.facing}, ${off}, ${b.rel.length} },\n`);
    off += b.rel.length;
  }
  W('};\n\n');
  W(`#define CT_GATO_FACE_NTILE 0x${NTILE.toString(16).toUpperCase()}\n`);
  baked.forEach((b, k) => {
    W(`// ${b.name} tile sheet (capture VRAM OBJ half, body md5 ${b.md5})\n`);
    W(`static const uint8_t ctGatoFaceTiles${k}[CT_GATO_FACE_NTILE][32] = {\n`);
    W(sheetRows(b.tiles));
    W('};\n');
  });
  W('static const uint8_t (*const ctGatoFaceTilesTab[3])[32] = { ctGatoFaceTiles0, ctGatoFaceTiles1, ctGatoFaceTiles2 };\n');
  W('#endif\n');
  return out.join('');
};

const bake = (name: string, facing: number, dump: PeekDump): Baked => {
  const cells = cellsOf(decodeOam(oamBlob(dump.oam))).sort((a, b) => a.idx - b.idx);
  const [lx, ly] = gatoFoot(dump.wram);
  const tiles = [...new Set(cells.map((c) => c.tile))].sort((a, b) => a - b);
  const flips = cells.filter((c) => c.hflip || c.vflip).length;
  if (flips !== 0) throw new Error('dossier 2.4: hf=vf=0 in every facing');
  return {
    name,
    facing,
    rel: cells.map((c) => ({ rx: c.x - lx, ry: c.y - ly, tile: c.tile })),
    tiles: tileSheet(dump.vram),
    md5: bodyMd5(dump.vram, tiles),
  };
};

/** tools/gen/battle_gato_faces.py: GATO's directional facing pose bakes (src/data/battle_gato_faces.h). */
const genBattleGatoFaces = async (ctx: ImportContext): Promise<GenFiles> => {
  const state = await recipeState(ctx, 'battle_gato_press_action');
  const oracle = peekOracle(ctx);
  const capture = (n: number): Promise<PeekDump> => oracle.peek({ state, script: `100:8,0:${n - 8}` });

  const idle = await capture(400);
  const cellsI = cellsOf(decodeOam(oamBlob(idle.oam)));
  const [fx, fy] = gatoFoot(idle.wram);
  if (fx !== 136 || fy !== 111) throw new Error('idle control capture not at the staged home foot (136,111)');
  const minx = Math.min(...cellsI.map((s) => s.x));
  const miny = Math.min(...cellsI.map((s) => s.y));
  if (minx - fx !== -32) throw new Error(`idle X extent ${minx - fx} != the A8.1 -32`);
  if (!(miny - fy >= -56 && miny - fy <= -50)) throw new Error(`idle Y rel ${miny - fy} outside the observed idle band`);

  const baked: Baked[] = [];
  for (const [name, facing, frame] of [['GF0_up', 0, 813], ['GF2_left', 2, 749], ['GF3_right', 3, 902]] as const) {
    baked.push(bake(name, facing, await capture(frame)));
  }
  if (new Set(baked.map((b) => b.md5)).size !== baked.length) {
    throw new Error('facing tile content must be DISTINCT (2.4)');
  }
  return { 'battle_gato_faces.h': emit(baked) };
};

export { genBattleGatoFaces };

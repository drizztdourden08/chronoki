/* @layer shared-asset-extraction @kind logic */
import { H, W } from './frames';

const BTN0 = '0:8';
const BTN1 = '0:6,20:2,0:40';

/** atbsel.py emit: the header up to the patch (the typewriter block follows). */
const emitMain = (
  pal: number[],
  idx0: number[][],
  patch: number[][],
  px0: number,
  py0: number,
  pw: number,
  ph: number,
): string => {
  const o: string[] = [];
  o.push('// AUTO-GENERATED by tools/gen/atbsel.py -- DO NOT EDIT.\n');
  o.push('// CT new-game ATB BATTLE-MODE selector (Active/Wait), baked byte-exact from the oracle.\n');
  o.push('// Dossier: disasm/notes/battle_atbmode.md PART 1/PART 2(A). Menu mode-3 screen 0x0D, handler\n');
  o.push('// C2/E1E3, shown at new-game start BEFORE the Crono naming step. Cursor $0054 (0=ACTIVE\n');
  o.push('// default row, 1=WAIT); A-confirm writes $2990 bit6 (C2/E24C TSB row0/TRB row1).\n');
  o.push('// Two baked FULL FRAMES (this screen has exactly 2 static states, unlike the dynamic naming\n');
  o.push('// screen): ROW0 verbatim + a ROW1 override PATCH (the only rect that differs -- description\n');
  o.push(`// text + hand cursor; verified 0/${W * H} mismatch reconstructing ROW1 = ROW0+patch).\n`);
  o.push(`// Captured saves/battle_re/atb_vram.state, btnscript "${BTN0}" (ACTIVE) / "${BTN1}" (WAIT).\n`);
  o.push('#ifndef CT_ATBSEL_H\n#define CT_ATBSEL_H\n#include <stdint.h>\n\n');
  o.push(`#define CT_ATBSEL_W ${W}\n#define CT_ATBSEL_HGT ${H}\n`);
  o.push(`#define CT_ATBSEL_NPAL ${pal.length}\n\n`);
  o.push('static const uint8_t ctAtbSelPal[CT_ATBSEL_NPAL][3] = {\n');
  for (const c of pal) o.push(`  {${c >> 16},${(c >> 8) & 255},${c & 255}},\n`);
  o.push('};\n\n');
  o.push('// ROW0 (ACTIVE, default cursor) full frame, palette indices [y][x].\n');
  o.push('static const uint8_t ctAtbSelFrame0[CT_ATBSEL_HGT][CT_ATBSEL_W] = {\n');
  for (const row of idx0) o.push(`  {${row.join(',')}},\n`);
  o.push('};\n\n');
  o.push('// ROW1 (WAIT) override patch: blit ctAtbSelFrame0 THEN this patch at (X,Y) to reproduce ROW1.\n');
  o.push(`#define CT_ATBSEL_PATCH_X ${px0}\n#define CT_ATBSEL_PATCH_Y ${py0}\n`);
  o.push(`#define CT_ATBSEL_PATCH_W ${pw}\n#define CT_ATBSEL_PATCH_H ${ph}\n\n`);
  o.push('static const uint8_t ctAtbSelPatch1[CT_ATBSEL_PATCH_H][CT_ATBSEL_PATCH_W] = {\n');
  for (const row of patch) o.push(`  {${row.join(',')}},\n`);
  o.push('};\n\n');
  o.push('#endif // CT_ATBSEL_H\n');
  return o.join('');
};

export { BTN0, BTN1, emitMain };

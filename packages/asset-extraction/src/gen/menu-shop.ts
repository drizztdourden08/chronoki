/* @layer shared-asset-extraction @kind logic */
import type { ImportContext } from '../pipeline/import-context.type';
import { cgWord, x5 } from './ctgen/menugfx';
import { cgramOf, peek, recipeState } from './ctgen/require-tools';
import { crlf, hx } from './ctgen/text-file';
import { DRIVES, TMW, TMH, BASE, NTILE } from './menu-shop.constants';
import type { Capture } from './menu-shop.type';

const same = (a: ArrayLike<number>, b: ArrayLike<number>): boolean => a.length === b.length && Array.from(a).every((v, i) => v === b[i]);

const capture = async (ctx: ImportContext, state: Uint8Array, btn: string, frames: number): Promise<Capture> => {
  const out = await peek(ctx, state, btn, { frames });
  if (out.wram[0x67] !== 0x0c) throw new Error(`menu_shop: the shop did not open ($0067 = ${hx(out.wram[0x67] as number, 2)}, not 0C)`);
  const map = Array.from({ length: TMW * 64 }, (_, i) => (out.vram[BASE * 2 + i * 2] as number) | ((out.vram[BASE * 2 + i * 2 + 1] as number) << 8));
  return { map, tiles: out.vram.slice(0x100 * 32, 0x188 * 32), cg: cgramOf(out) };
};

const checkAgree = (caps: Capture[]): void => {
  const [a, b, c] = caps as [Capture, Capture, Capture];
  if (!(same(a.map, b.map) && same(b.map, c.map))) throw new Error('the shop chrome changed between its states');
  if (!(same(a.tiles, b.tiles) && same(b.tiles, c.tiles))) throw new Error('the narrow-digit tiles changed between its states');
  for (let p = 0; p < 8; p += 1) {
    const row = (x: Capture): Uint8Array => x.cg.subarray(p * 32, p * 32 + 8);
    if (!(same(row(a), row(b)) && same(row(b), row(c)))) throw new Error(`the palette ${p} changed between the shop states`);
  }
  for (let t = 0; t < NTILE; t += 1) {
    if (a.tiles.subarray(t * 32 + 16, t * 32 + 32).some((v) => v !== 0)) {
      throw new Error(`tile ${hx(0x100 + t, 3)} uses planes 2/3`);
    }
  }
};

const mapRows = (tm: number[]): string[] =>
  Array.from({ length: TMH }, (_, ty) => `  ${tm.slice(ty * TMW, (ty + 1) * TMW).map((e) => `0x${hx(e, 4)}`).join(', ')},`);

const pal3 = (cg: Uint8Array, p: number): string =>
  Array.from({ length: 4 }, (_, i) => {
    const w = cgWord(cg, p * 16 + i);
    return `{${x5(w & 31)},${x5((w >> 5) & 31)},${x5((w >> 10) & 31)}}`;
  }).join(',');

const render = (tm: number[], tq: number[], tiles: Uint8Array, cg: Uint8Array): string => {
  const lines = [
    '// GENERATED by tools/_gen_menuchrome_shop.py -- do not edit. The SHOP screen ($0C) BG2 chrome,',
    '// captured from the oracle (VRAM word 0x6000) on its Buy/Sell, Buy-list and quantity states (identical).',
    '#ifndef CT_MENU_SHOP_H',
    '#define CT_MENU_SHOP_H',
    '#include <stdint.h>',
    'static const uint16_t ctMenuChromeShopTM[CT_MENU_CHROME_TMW*CT_MENU_CHROME_TMH] = {',
    ...mapRows(tm),
    '};',
    '// Map rows 32-59 (the same capture): C2:C213 draws BOTH layouts into $7E:3E00 at init, and the equip sub-mode',
    '// shows the second by BG2 V = $0D0A | $0D0B << 8 (C2/85D6): $0D0B = 00 (C2/E0DC) gives 255, i.e. line y + 256.',
    'static const uint16_t ctMenuChromeShopEquipTM[CT_MENU_CHROME_TMW*CT_MENU_CHROME_TMH] = {',
    ...mapRows(tq),
    '};',
    '// BG1 tiles 0x100-0x187 as the shop screen has them (2bpp in planes 0/1 of a 4bpp tile; 16 B each):',
    '// the narrow one- and two-digit glyphs C2/DE56 composes the party panel numbers from (tile 0x16E + v/10,',
    '// then 0x100 + v%100 or 0x164 + v). Their SOURCE is not derived (shop_screen.md 11.2) -- captured.',
    'static const uint8_t ctShopNarrowTiles[0x88][16] = {',
    ...Array.from({ length: NTILE }, (_, t) => `  {${Array.from(tiles.subarray(t * 32, t * 32 + 16), (b) => `0x${hx(b, 2)}`).join(',')}},`),
    '};',
    '// BG palettes 0-7 (indices 0-3), CGRAM on the shop screen, (v<<3)|(v>>2): C2/DE62 picks 0 equal, 2 better,',
    '// 7 worse for the panel numbers; C2/EC93 moves a dimmed member to (p & 3) | 4 (4 / 6 / 7), C2/A3ED dims to 7.',
    'static const uint8_t ctShopTextPal[8][4][3] = {',
    ...Array.from({ length: 8 }, (_, p) => `  {${pal3(cg, p)}},`),
    '};',
    '#endif',
    '',
  ];
  return crlf(lines.join('\n'));
};

const genMenuShop = async (ctx: ImportContext): Promise<string> => {
  const state = await recipeState(ctx, 'menu_shop');
  const caps: Capture[] = [];
  for (const [, btn, frames] of DRIVES) caps.push(await capture(ctx, state, btn, frames));
  checkAgree(caps);
  const first = caps[0] as Capture;
  const tm = first.map.slice(0, TMW * TMH);
  const tq = first.map.slice(32 * TMW, (32 + TMH) * TMW);
  const ok = [...tm, ...tq].every((e) => ((e & 0x3ff) === 0 || (e & 0x3ff) >= 0x3dc && (e & 0x3ff) <= 0x3ef) && ((e >> 10) & 7) === 0);
  if (!ok) throw new Error('menu_shop: a chrome cell is not a window tile on palette 0');
  return render(tm, tq, first.tiles, first.cg);
};

export { genMenuShop };

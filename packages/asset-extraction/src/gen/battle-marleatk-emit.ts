/* @layer shared-asset-extraction @kind logic */
import { dec, hexN } from './shared/py-format';
import type { Sprite } from './shared/oam-decode';

const NTILE = 0xa0;

interface MarleKf {
  pose: string;
  rf: number;
  ax: number;
  ay: number;
  on: Sprite[];
  tiles: Uint8Array[];
}

interface SparkKf {
  pose: string;
  rf: number;
  spr: Sprite;
  vram: Uint8Array;
}

/** [frame, dx, dy, poseId] */
type TrajRow = [number, number, number, number];

const bytes = (t: Uint8Array): string => Array.from(t, (b) => `0x${hexN(b, 2)}`).join(',');

const marleBlock = (mkfs: MarleKf[]): string => {
  const obj = mkfs.flatMap((kf) => kf.on);
  let off = 0;
  const kfLines = mkfs.map((kf, i) => {
    const line = `  { "Marle", "${kf.pose}", 6, ${kf.rf}, ${kf.rf}, ${off}, ${kf.on.length}, ${i}, ${kf.ax}, ${kf.ay} },\n`;
    off += kf.on.length;
    return line;
  });
  return [
    `#define CT_MARLEATK_NOBJ ${obj.length}\n`,
    'static const CtAnimObj ctMarleAtkObj[CT_MARLEATK_NOBJ] = {\n',
    ...obj.map(
      (s) =>
        `  { ${s.idx}, ${dec(s.x, 4)}, ${dec(s.y, 3)}, 0x${hexN(s.tile, 3)}, ${s.pal}, ${s.prio}, ${s.hflip}, ${s.vflip} },\n`,
    ),
    `};\n#define CT_MARLEATK_NKF ${mkfs.length}\n`,
    'static const CtAnimKeyframe ctMarleAtkKf[CT_MARLEATK_NKF] = {\n',
    ...kfLines,
    '};\n',
    'static const uint8_t ctMarleAtkTiles[CT_MARLEATK_NKF][CT_ANIM_NTILE][32] = {\n',
    ...mkfs.flatMap((kf) => [`  { // ${kf.pose}\n`, ...kf.tiles.map((t) => `    {${bytes(t)}},\n`), '  },\n']),
    '};\n\n',
  ].join('');
};

const sparkBlock = (skfs: (SparkKf | null)[]): string => {
  const sv = skfs.filter((k): k is SparkKf => k !== null);
  return [
    '// IMPACT SPARK: single pal0 OBJ at the bolt-impact point, tile-animated. dx/dy = OAM pos.\n',
    'typedef struct { const char* pose; uint16_t repF; uint16_t tile; int16_t x; uint8_t y; } CtSparkKf;\n',
    `#define CT_MARLESPARK_NKF ${sv.length}\n`,
    'static const CtSparkKf ctMarleSparkKf[CT_MARLESPARK_NKF] = {\n',
    ...sv.map((kf) => `  { "${kf.pose}", ${kf.rf}, 0x${hexN(kf.spr.tile, 3)}, ${kf.spr.x}, ${kf.spr.y} },\n`),
    '};\n',
    '// spark tiles keyed absolute (0x100-0x12F); 16x16 uses T,T+1,T+0x10,T+0x11.\n',
    'static const uint8_t ctMarleSparkTiles[CT_MARLESPARK_NKF][4][32] = {\n',
    ...sv.flatMap((kf) => {
      const t = kf.spr.tile;
      return [
        `  { // ${kf.pose} tile 0x${hexN(t, 3)}\n`,
        ...[t, t + 1, t + 0x10, t + 0x11].map((q) => {
          const o = (q & 0x1ff) * 32;
          return `    {${bytes(kf.vram.subarray(o, o + 32))}},\n`;
        }),
        '  },\n',
      ];
    }),
    '};\n\n',
  ].join('');
};

const trajBlock = (traj: TrajRow[]): string =>
  [
    '// per-frame (dx,dy rel home 164,63 ; poseId 0..3) over the attack. Strike (GATO flash) ~f939.\n',
    'typedef struct { int16_t dx; int8_t dy; uint8_t pose; } CtMarleAtkStep;\n',
    `#define CT_MARLEATK_TRAJ_F0 ${(traj[0] as TrajRow)[0]}\n#define CT_MARLEATK_TRAJ_N ${traj.length}\n`,
    'static const CtMarleAtkStep ctMarleAtkTraj[CT_MARLEATK_TRAJ_N] = {\n',
    ...traj.map(([f, dx, dy, p]) => `  { ${dec(dx, 4)}, ${dec(dy, 3)}, ${p} }, // f${f}\n`),
    '};\n#define CT_MARLEATK_STRIKE_F 939\n',
    '#endif\n',
  ].join('');

/** The text of battle_marleatk.h (emit). */
const emitMarleAtk = (mkfs: MarleKf[], skfs: (SparkKf | null)[], traj: TrajRow[]): string =>
  [
    '// AUTO-GENERATED by tools/gen/battle_marleatk.py -- DO NOT EDIT. NOT WIRED.\n',
    '// MARLE crossbow ATTACK ($9877=0x0F, script CD/7164, AEEB=02 PC_RANGED). battle_actionfx.md ADD-MA.\n',
    '#ifndef CT_BATTLE_MARLEATK_H\n#define CT_BATTLE_MARLEATK_H\n#include <stdint.h>\n#include "battle_anim.h"\n\n',
    marleBlock(mkfs),
    sparkBlock(skfs),
    trajBlock(traj),
  ].join('');

export type { MarleKf, SparkKf, TrajRow };
export { emitMarleAtk, NTILE };

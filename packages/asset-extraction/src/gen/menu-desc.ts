/* @layer shared-asset-extraction @kind logic */
import { decodeString } from '../extract/text-tokens';
import { loadDict } from '../extract/load-dict';

/** CC/2EB1 as a HiROM file offset: the table of 16-bit local pointers into bank $CC, one per item id. */
const BASE = 0x0c2eb1;
const N = 242;

/** The C string literal of one description; the closing quote U+201D is the raw CT code 0xE2 (the `""` ends the hex escape). */
const cString = (s: string): string =>
  `"${s.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('\u201d', '\\xE2""')}"`;

/** tools/gen/menu_desc.py: the item/equipment description strings as src/data/menu_desc.h. */
const genMenuDesc = (rom: Uint8Array): string => {
  const subs = loadDict(rom);
  const ptrs: number[] = [];
  for (let i = 0; i < N; i += 1) ptrs.push((rom[BASE + i * 2] as number) | ((rom[BASE + i * 2 + 1] as number) << 8));
  const minPtr = Math.min(...ptrs);
  const tableEnd = (BASE & 0xffff) + N * 2;
  if (minPtr !== tableEnd) {
    throw new Error(`the table does not end where its first string begins -- N is wrong: min ptr ${minPtr.toString(16)}, table end ${tableEnd.toString(16)}`);
  }
  const desc = ptrs.map((p) => decodeString(rom, 0x0c0000 + p, subs, { namesub: true }));
  if (desc.some((s) => s.includes('\x01'))) throw new Error('an item description holds a name or number code');
  const width = Math.max(...desc.map((s) => s.length)) + 1;
  const nonEmpty = desc.filter((s) => s !== '').length;
  const out = [
    '// GENERATED by tools/gen/menu_desc.py -- do not edit.',
    "// The ROM's STORED item/equipment description strings: the pointer table at CC/2EB1",
    '// (16-bit local pointers into bank $CC), indexed by item id, staged by C2/F2F3 through',
    `// $020C/$020D-$020F and rendered by C2/FA49. ${N} entries ($00..$F1), ${nonEmpty} of them non-empty.`,
    "// An EMPTY string is the ROM's own answer, not a gap: 137 ids describe nothing.",
    '#ifndef CT_MENU_DESC_H',
    '#define CT_MENU_DESC_H',
    '',
    `static const char ctItemDesc[${N}][${width}] = {`,
  ];
  for (let i = 0; i < N; i += 2) out.push(`  ${desc.slice(i, i + 2).map(cString).join(', ')},`);
  out.push('};', '', '#endif');
  return `${out.join('\n')}\n`;
};

export { genMenuDesc };

/* @layer shared-asset-extraction @kind logic */
import type { ImportContext } from '../pipeline/import-context.type';
import { peekOracle, recipeState, teleportState } from '../oracle/peek-access';
import { requireBytes } from '../pipeline/work-files';
import type { GenFiles } from './oracle-gen-stage.type';
import { rgbOfFb } from './shared/fb-decode';
import { CELL_X, CELL_Y, CELL_W, CELL_H, FB_OFFSET, DRIVE } from './dlg-cursor.constants';

const sameRgb = (a: Uint8Array, ao: number, b: Uint8Array, bo: number): boolean =>
  a[ao] === b[bo] && a[ao + 1] === b[bo + 1] && a[ao + 2] === b[bo + 2];

const genDlgCursor = async (ctx: ImportContext): Promise<GenFiles> => {
  const start = await recipeState(ctx, 'truce_market');
  const lab = await teleportState(ctx, start, { scene: 434, tx: 8, ty: 8, facing: 0, frames: 240 });
  const fb = rgbOfFb((await peekOracle(ctx).peek({ state: lab, script: DRIVE, rule: true })).fb);
  const w = await requireBytes(ctx.work, 'saves/ct_window.bin');
  const hgt = w[0] as number;
  const px = w.subarray(1);
  if (px.length < 256 * hgt * 3) throw new Error('dlg_cursor: window bitmap truncated');
  const rgba: number[][] = [];
  let opaque = 0;
  for (let y = 0; y < CELL_H; y += 1) {
    for (let x = 0; x < CELL_W; x += 1) {
      const wx = CELL_X + x;
      const wy = CELL_Y + y;
      const o = ((wy + FB_OFFSET) * 256 + wx) * 3;
      if (sameRgb(fb, o, px, (wy * 256 + wx) * 3)) rgba.push([0, 0, 0, 0]);
      else {
        rgba.push([fb[o] as number, fb[o + 1] as number, fb[o + 2] as number, 255]);
        opaque += 1;
      }
    }
  }
  if (opaque < 40) throw new Error(`dlg_cursor: only ${opaque} opaque pixels -- wrong frame or misaligned cell`);
  const L = [
    '// GENERATED by tools/gen_dlgcursor.py -- do not hand-edit.',
    '// The dialogue DECISION CURSOR (pointing hand), lifted from an oracle frame by',
    '// subtracting the dialogue window texture (see the generator docstring for the',
    `// capture). ${CELL_W}x${CELL_H}, RGBA8888 row-major, alpha 0 = window shows through.`,
    `// Cell in window space: (${CELL_X},${CELL_Y})-(${CELL_X + CELL_W - 1},${CELL_Y + CELL_H - 1}); ${opaque} opaque pixels.`,
    '#ifndef GEN_DLG_CURSOR_H\n#define GEN_DLG_CURSOR_H',
    `#define DLGCURSOR_W ${CELL_W}\n#define DLGCURSOR_H ${CELL_H}`,
    `static const unsigned char dlgCursorRGBA[${CELL_W} * ${CELL_H} * 4] = {`,
  ];
  for (let y = 0; y < CELL_H; y += 1) {
    L.push(`  ${rgba.slice(y * CELL_W, (y + 1) * CELL_W).map((q) => q.join(',')).join(',')},`);
  }
  L.push('};', '#endif');
  return { 'dlg_cursor.h': `${L.join('\n')}\n` };
};

export { genDlgCursor };

/* @layer shared-asset-extraction @kind logic */
import type { ImportContext } from '../pipeline/import-context.type';
import { requireBytes } from '../pipeline/work-files';
import { peek, recipeState, requireTools, rgbOfFb } from './ctgen/require-tools';
import { crlf } from './ctgen/text-file';

const CELL_X = 16;
const CELL_Y = 10;
const CELL_W = 16;
const CELL_H = 12;
/** Peek dumps are 240 rows; the box's top row 0 lands at fb y 16. */
const FB_OFFSET = 16;
const DRIVE = '10:8,0:6,100:6,0:180,100:6,0:60,100:6,0:60,100:6,0:120,100:6,0:120';

type Pixel = [number, number, number, number];

const same = (a: Uint8Array, ai: number, b: Uint8Array, bi: number): boolean =>
  a[ai] === b[bi] && a[ai + 1] === b[bi + 1] && a[ai + 2] === b[bi + 2];

/** Whatever differs from the window texture inside the fixed cell is the cursor. */
const liftCursor = (fb: Uint8Array, window: Uint8Array): { rgba: Pixel[]; opaque: number } => {
  const px = window.subarray(1);
  const height = window[0] as number;
  if (px.length < 256 * height * 3) throw new Error('dlg_cursor: window bitmap truncated');
  const rgba: Pixel[] = [];
  let opaque = 0;
  for (let y = 0; y < CELL_H; y += 1) {
    for (let x = 0; x < CELL_W; x += 1) {
      const wx = CELL_X + x;
      const wy = CELL_Y + y;
      const o = ((wy + FB_OFFSET) * 256 + wx) * 3;
      if (same(fb, o, px, (wy * 256 + wx) * 3)) {
        rgba.push([0, 0, 0, 0]);
      } else {
        rgba.push([fb[o] as number, fb[o + 1] as number, fb[o + 2] as number, 255]);
        opaque += 1;
      }
    }
  }
  return { rgba, opaque };
};

const render = (rgba: Pixel[], opaque: number): string => {
  const rows: string[] = [];
  for (let y = 0; y < CELL_H; y += 1) {
    rows.push(`  ${rgba.slice(y * CELL_W, (y + 1) * CELL_W).map((q) => q.join(',')).join(',')},`);
  }
  return [
    '// GENERATED by tools/gen_dlgcursor.py -- do not hand-edit.',
    '// The dialogue DECISION CURSOR (pointing hand), lifted from an oracle frame by',
    '// subtracting the dialogue window texture (see the generator docstring for the',
    `// capture). ${CELL_W}x${CELL_H}, RGBA8888 row-major, alpha 0 = window shows through.`,
    `// Cell in window space: (${CELL_X},${CELL_Y})-(${CELL_X + CELL_W - 1},${CELL_Y + CELL_H - 1}); ${opaque} opaque pixels.`,
    '#ifndef GEN_DLG_CURSOR_H',
    '#define GEN_DLG_CURSOR_H',
    `#define DLGCURSOR_W ${CELL_W}`,
    `#define DLGCURSOR_H ${CELL_H}`,
    `static const unsigned char dlgCursorRGBA[${CELL_W} * ${CELL_H} * 4] = {`,
    ...rows,
    '};',
    '#endif',
    '',
  ].join('\n');
};

/** tools/gen/dlg_cursor.py: the dialogue decision cursor (the pointing hand), lifted out of an oracle frame. */
const genDlgCursor = async (ctx: ImportContext): Promise<string> => {
  const start = await recipeState(ctx, 'truce_market');
  const lab = await requireTools(ctx).teleport({ start, scene: 434, tx: 8, ty: 8, facing: 0, frames: 240 });
  const fb = rgbOfFb((await peek(ctx, lab, DRIVE)).fb);
  const window = await requireBytes(ctx.work, 'saves/ct_window.bin');
  const { rgba, opaque } = liftCursor(fb, window);
  if (opaque < 40) throw new Error(`dlg_cursor: only ${opaque} opaque pixels -- wrong frame or misaligned cell`);
  return crlf(render(rgba, opaque));
};

export { genDlgCursor };

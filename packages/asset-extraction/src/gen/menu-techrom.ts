/* @layer shared-asset-extraction @kind logic */
import { romRegion } from '../rom/hirom';
import { decodeString } from '../extract/text-tokens';
import { loadDict } from '../extract/load-dict';
import { cArray } from './c-array';
import { IDX_LO, IDX_HI, DESC_N, TECH_N } from './menu-techrom.constants';

const mpIndexTable = (rom: Uint8Array): Uint8Array => {
  const idx = new Uint8Array(IDX_HI - IDX_LO);
  const put = (charId: number, techId: number, v: number): void => {
    const a = 0x1607 + charId * 64 + techId;
    if (a >= IDX_LO && a < IDX_HI) idx[a - IDX_LO] = v;
  };
  const r = (a: number): number => rom[a] as number;
  let tech = 0x39;
  for (let pair = 0; pair < 15; pair += 1) {
    const a = r(0x0c24b4 + pair * 3);
    const b = r(0x0c24b5 + pair * 3);
    for (let k = 0; k < 3; k += 1) {
      put(a, tech, r(0x0c28db + pair * 6 + k * 2));
      put(b, tech, r(0x0c28db + pair * 6 + k * 2 + 1));
      tech += 1;
    }
  }
  let run = 0;
  tech = 0x66;
  for (let tri = 0; tri < 15; tri += 1) {
    const m = r(0x0c2979 + tri);
    for (let c = 0; c < 8; c += 1) {
      if (m & (0x80 >> c)) {
        put(c, tech, r(0x0c2935 + run));
        run += 1;
      }
    }
    tech += 1;
  }
  return idx;
};

const techDescriptions = (rom: Uint8Array): string[] => {
  const subs = loadDict(rom);
  const desc: string[] = [];
  for (let tid = 0; tid < DESC_N; tid += 1) {
    const ptr = (rom[0x0c3a09 + tid * 2] as number) | ((rom[0x0c3a0a + tid * 2] as number) << 8);
    let t: string;
    try {
      t = decodeString(rom, 0x0c0000 + ptr, subs);
    } catch {
      t = '';
    }
    const first = t.split('\n')[0] as string;
    desc.push(
      [...first]
        .filter((ch) => ch.charCodeAt(0) >= 32 && ch.charCodeAt(0) < 127)
        .join('')
        .slice(0, 31),
    );
  }
  return desc;
};

const emit = (name: string, data: Uint8Array, note: string): string[] => [`// ${note}`, ...cArray('uint8_t', name, data)];

const castTables = (rom: Uint8Array): { fxb: Uint8Array; nib: Uint8Array } => {
  const fxb = new Uint8Array(TECH_N);
  const nib = new Uint8Array(TECH_N);
  for (let t = 0; t < TECH_N; t += 1) {
    const rec = 0x0c2140 + t * 12;
    nib[t] = (rom[rec] as number) & 0x1f;
    const allp = ((((rom[0x0c1acb + t * 2] as number) & 1) + 1) << 2);
    fxb[t] = ((rom[rec + 1] as number) & 0xc0) | allp;
  }
  return { fxb, nib };
};

const genMenuTechrom = (rom: Uint8Array): string => {
  const idx = mpIndexTable(rom);
  const desc = techDescriptions(rom);
  const { fxb, nib } = castTables(rom);
  const out = [
    "// GENERATED by tools/gen/menu_techrom.py -- do not edit. The TECH screen's ROM data.",
    '// See the script header and disasm/notes/menu2_tech_screen.md for every address.',
    '#ifndef CT_MENU_TECHROM_H',
    '#define CT_MENU_TECHROM_H',
    '#include <stdint.h>',
    ...emit('ctTechBound', romRegion(rom, 0x2bd40, 0x2bd40 + 38), 'C2/BD40 -- cumulative tech-id boundary over the 37 groups (38 bytes)'),
    ...emit('ctTechTabWin', romRegion(rom, 0x2bd65, 0x2bd65 + 6), 'C2/BD65 -- (firstGroup, count) per tab: Single 0..6, Double 7..21, Triple 22..36'),
    ...emit('ctTechGroupMask', romRegion(rom, 0x0c2963, 0x0c2963 + 37), 'CC/2963 -- the CHARACTERS in each group (bit 0x80 = charId 0); C2/BCCD\'s filter'),
    ...emit('ctTechNextCap', romRegion(rom, 0x3ff951, 0x3ff951 + 8), 'FF/F951 -- per-character cap on the not-yet-learned tech FF/F876 adds to the menu bitfield'),
    ...emit('ctTechMpCost', romRegion(rom, 0x0c253b, 0x0c253b + 0x100), 'CC/253B -- MP cost, indexed by techId (Single) or by ctTechMpIdx (Double/Triple)'),
    '// CC/3A09 + id*2 -> the dictionary-compressed DESCRIPTION string, decoded here.',
    '// Entries 0x76..0x78 are the Single/Double/Triple TAB names.',
    `static const char ctTechDesc[${DESC_N}][32] = {`,
    ...desc.map((t) => `  "${t.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}",`),
    '};',
    ...emit('ctTechFx', fxb, '$0DBD per tech id (C2/B3E6): b7 restore HP, b6 restore MP, b3 ALL PARTY'),
    ...emit('ctTechNib', nib, '$0DC0 per tech id = CC/2140[id*12] & 0x1F -- the amount multiplier'),
    ...emit('ctTechRng', romRegion(rom, 0x00fe00, 0x00fe00 + 0x110), 'C0/FE00 -- the per-target spread table; C2/8ECC indexes it with NO wrap, hence the tail'),
    ...emit('ctTechCastPose', romRegion(rom, 0x2b519, 0x2b519 + 7), 'C2/B519 -- $19E1, the caster pose, indexed by charId (SEVEN entries: Ayla is 5)'),
    ...emit('ctTechMpIdx', idx, '$7E:1640..17FB, rebuilt per FF/F8BD-F94B: index it [charId*64 + techId - 0x39] to get the CC/253B index a DOUBLE/TRIPLE costs THIS character'),
    '#endif',
  ];
  return `${out.join('\n')}\n`;
};

export { genMenuTechrom };

import { romRegion } from '../rom/rom-region';
import { cArray, hex } from './c-text';

const CC: [number, number] = [0x0c0b5e, 0x0c257b];
const C2: [number, number] = [0x02bd40, 0x02c5b3];
const CFG: [number, number] = [0x3fd3fe, 0x3fd57a];
const MC: [number, number] = [0x03ff951, 0x03ff959];
const NAV: [number, number] = [0x3fb5a0, 0x3fb5a0 + 21 * 6];
const CDEF: [number, number] = [0x02fca6, 0x02fca6 + 12];

/** The item-category string of item `idv` (FF/B310 pointer table -> FF-bank CT-text), as ASCII. */
const catName = (rom: Uint8Array, idv: number): string => {
  const pe = 0x3fb310 + idv * 2;
  const so = 0x3f0000 + ((rom[pe] as number) | ((rom[pe + 1] as number) << 8));
  let s = '';
  for (let i = 0; i < 16; i += 1) {
    const c = rom[so + i] as number;
    if (c === 0) break;
    if (c >= 0xa0 && c <= 0xb9) s += String.fromCharCode(65 + c - 0xa0);
    else if (c >= 0xba && c <= 0xd3) s += String.fromCharCode(97 + c - 0xba);
    else if (c >= 0xd4 && c <= 0xdd) s += String.fromCharCode(48 + c - 0xd4);
    else if (c === 0xef || c === 0xff) s += ' ';
  }
  return s.trim();
};

const table = (rom: Uint8Array, name: string, [lo, hi]: [number, number], withBase: boolean): string[] => [
  ...(withBase ? [`#define ${name.toUpperCase()}_BASE 0x${hex(lo, 6)}u`] : []),
  ...cArray('uint8_t', name, romRegion(rom, lo, hi)),
];

const ITEM_NAV_NOTE = [
  "// FF/B53E -- the ITEM screen's cursor graph, 15 records x 6 bytes, copied verbatim to $7E:9380 by the",
  '// screen builder exactly as FF/B5A0 (below) is on Config. Records 0..9 are the ten list rows at',
  '// (24, 87 + 12*row), 10/11 the Use/Move labels, 12..14 the target-select party cells; bytes +2..+5 are',
  "// the Up/Down/Left/Right neighbours. VERIFIED byte-identical to the oracle's live $7E:9380 on its own",
  '// Item-screen capture, whose cursor OAM $0770 = (0x18, 0x57) = record 0.',
  '#define CTITEMNAV_BASE 0x3FB53Eu',
];
const FONT_NOTE = [
  "// FF/C9FC -- sixteen 2bpp tiles the menu's graphics build C2/968D DMAs (C2/9542) over tiles 0x30-0x3F of",
  '// its font copy at $7E:5000 (FF/8E60 = FF/8C60\'s tile 0x20 on): 0x30 #, 0x31 the arrow, 0x32-0x34 frame/+,',
  "// 0x35-0x3F bold letters. Measured: the oracle's menu VRAM holds them at BG3 $E000 and BG1 4bpp tile 0x30+.",
];

/** tools/gen/menu_romdata.py: the menu's ROM data tables as src/data/menu_romdata.h. */
const genMenuRomdata = (rom: Uint8Array): string => {
  const out = [
    "// GENERATED by tools/gen/menu_romdata.py -- do not edit. The menu's ROM data tables, extracted",
    '// once so the runtime menu needs no .sfc (RE re-impl, not emulation). See the script header.',
    '#ifndef CT_MENU_ROMDATA_H\n#define CT_MENU_ROMDATA_H\n#include <stdint.h>',
    ...table(rom, 'ctRomCC', CC, true),
    ...table(rom, 'ctRomC2', C2, true),
    ...table(rom, 'ctRomCfg', CFG, true),
    ...table(rom, 'ctRomMaxCnt', MC, true),
    ...ITEM_NAV_NOTE,
    ...table(rom, 'ctItemNav', [0x3fb53e, 0x3fb53e + 15 * 6], false),
    ...table(rom, 'ctCfgNav', NAV, true),
    ...table(rom, 'ctCfgDefaults', CDEF, true),
    ...FONT_NOTE,
    ...table(rom, 'ctMenuFontC9FC', [0x3fc9fc, 0x3fc9fc + 0x100], true),
    'static const char ctItemCat[256][12] = {',
  ];
  for (let idv = 0; idv < 256; idv += 1) {
    out.push(`  "${catName(rom, idv).slice(0, 11).replace(/"/g, '\\"')}",`);
  }
  out.push('};\n#endif');
  return `${out.join('\n')}\n`;
};

export { genMenuRomdata };

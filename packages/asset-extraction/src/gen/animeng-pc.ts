/* @layer shared-asset-extraction @kind logic */
import { romRegion } from '../rom/rom-region';
import { hex } from './c-text';
import { ANIMENG_E4_PC } from './animeng-pc-e4';

const STRIDE = 0x28;
const foff = (bank: number, addr: number): number => ((bank - 0xc0) << 16) | addr;
const sext = (b: number): number => (b >= 0x80 ? b - 256 : b);

interface PcConfig {
  base: number;
  sheet: number;
  /** Every E3 index the engine selects (idle + attack), sorted. */
  used: number[];
}

const PCS = ['Crono', 'Marle', 'Lucca', 'Frog'] as const;
const PC: Record<(typeof PCS)[number], PcConfig> = {
  Crono: { base: foff(0xdc, 0x27b0), sheet: foff(0xd2, 0x72c0), used: [0x20, 0x41, 0x47, 0x4f, 0x50, 0x51, 0x52, 0x53, 0x54, 0x8b, 0xc6, 0xc7, 0xd5] },
  Marle: { base: foff(0xdc, 0x9ad8), sheet: foff(0xd4, 0x0000), used: [0x37, 0x5b, 0x8c, 0x8d, 0xd9, 0xda] },
  Lucca: { base: foff(0xdc, 0x4e70), sheet: foff(0xd3, 0x6b40), used: [0x05, 0x08, 0x23, 0x2a, 0x31, 0x39, 0x3d, 0xa8, 0xa9, 0xaa, 0xec] },
  Frog: { base: foff(0xdc, 0x7490), sheet: foff(0xd3, 0x0000), used: [0x3b] },
};

const rec = (rom: Uint8Array, base: number, n: number): Uint8Array => romRegion(rom, base + n * STRIDE, base + n * STRIDE + STRIDE);
const positions = (r: Uint8Array): [number, number][] =>
  Array.from({ length: 4 }, (_, i) => [sext(r[0x20 + 2 * i] as number), sext(r[0x20 + 2 * i + 1] as number)]);
const cellwords = (r: Uint8Array): number[] => Array.from({ length: 16 }, (_, i) => (r[2 * i] as number) | ((r[2 * i + 1] as number) << 8));

const collectSrcs = (rom: Uint8Array, cfg: PcConfig): number[] => {
  const srcs = new Set<number>();
  for (const n of cfg.used) {
    for (const w of cellwords(rec(rom, cfg.base, n))) if (w & 0x07ff) srcs.add(w & 0x07ff);
  }
  return [...srcs].sort((a, b) => a - b);
};

const E3_HEAD = [
  '// GENERATED by tools/gen/animeng_pc.py -- do not edit.',
  '// PC (Crono/Marle) E3 sprite-ASSEMBLY records. Crono base $DC27B0 (live $1C78[0]); Marle base $DC9AD8',
  '// (live $1C78[3]). stride 0x28; record = [16 x 16-bit CELL-WORDS +0x00][4 signed (dx,dy) +0x20]',
  '//   (the 4-cell PC form of ADDENDUM 1). cell-word = srcTile[0:10] | Hflip[bit14]; word 0 = blank.',
  '//   raster: word i -> VRAM tile vt0 + (i%8) + 0x10*(i//8) (Crono/Lucca vt0=0x08, Marle/Frog vt0=0x20).',
  '//   tile order for the 4 (dx,dy): base vt0 + {0,2,4,6}. Lucca base $DC4E70 / Frog base $DC7490 (both',
  '//   bank-DC, stride 0x28, UNCOMPRESSED sheets in bank D3 -- battle_3pc_lucca_frog.md §1.1).',
  '#ifndef CT_ANIMENG_E3_PC_H',
  '#define CT_ANIMENG_E3_PC_H',
  '#include <stdint.h>',
  '',
  'typedef struct { int8_t dx, dy; } CtAnimengPcPos;              // OAM cell offset from the live foot',
  'typedef struct { uint8_t idx; CtAnimengPcPos pos[4]; uint16_t cw[16]; } CtAnimengPcRec;  // sparse',
  '',
];

const SHEET_HEAD = [
  '// GENERATED by tools/gen/animeng_pc.py -- do not edit.',
  '// PC sprite SHEETS baked STRAIGHT FROM ROM (PC sprites are uncompressed: Crono sheet $D272C0 =',
  '// live $1C57[0]; Marle sheet $D40000 = live $1C57[3]) -- so NO interim WRAM fixture (unlike GATO).',
  '// Sparse: only the srcTiles the used E3 records gather. 8x8 4bpp (0x20 B); flip cells bit-reverse',
  "// at RUNTIME (the cell-word's bit14), so these are the RAW (unflipped) sheet bytes.",
  '#ifndef CT_ANIMENG_SHEET_PC_H',
  '#define CT_ANIMENG_SHEET_PC_H',
  '#include <stdint.h>',
  '',
  'typedef struct { uint16_t src; uint8_t px[32]; } CtAnimengPcSheetTile;  // sorted by src -> lookup',
  '',
];

/** animeng_pc.py w_e3(). */
const writeE3 = (rom: Uint8Array): string => {
  const o = [...E3_HEAD];
  for (const who of PCS) {
    const cfg = PC[who];
    o.push(`#define CT_ANIMENG_E3_${who.toUpperCase()}_N ${cfg.used.length}`);
    o.push(`static const CtAnimengPcRec ctAnimengE3${who}[CT_ANIMENG_E3_${who.toUpperCase()}_N] = {`);
    for (const n of cfg.used) {
      const r = rec(rom, cfg.base, n);
      const pos = positions(r).map(([dx, dy]) => `{${dx},${dy}},`).join(' ');
      const cws = cellwords(r).map((w) => `0x${hex(w, 4)},`).join(' ');
      o.push(`  { 0x${hex(n, 2)}, { ${pos} }, { ${cws} } },`);
    }
    o.push('};', '');
  }
  o.push('#endif', '');
  return o.join('\n');
};

/** animeng_pc.py w_sheet(). */
const writeSheet = (rom: Uint8Array): string => {
  const o = [...SHEET_HEAD];
  for (const who of PCS) {
    const cfg = PC[who];
    const srcs = collectSrcs(rom, cfg);
    o.push(`#define CT_ANIMENG_SHEET_${who.toUpperCase()}_N ${srcs.length}`);
    o.push(`static const CtAnimengPcSheetTile ctAnimengSheet${who}[CT_ANIMENG_SHEET_${who.toUpperCase()}_N] = {`);
    for (const s of srcs) {
      const b = romRegion(rom, cfg.sheet + s * 0x20, cfg.sheet + s * 0x20 + 0x20);
      o.push(`  { 0x${hex(s, 3)}, {${Array.from(b, (x) => `0x${hex(x, 2)}`).join(',')}} },`);
    }
    o.push('};', '');
  }
  o.push('#endif', '');
  return o.join('\n');
};

/** tools/gen/animeng_pc.py: the three headers of the PC pose engine, by file name. */
const genAnimengPc = (rom: Uint8Array): Record<string, string> => ({
  'animeng_e3_pc.h': writeE3(rom),
  'animeng_sheet_pc.h': writeSheet(rom),
  'animeng_e4_pc.h': ANIMENG_E4_PC,
});

export { genAnimengPc };

/* @layer shared-asset-extraction @kind logic */
import { hex } from './c-text';
import { chromeImage, parseBake, tileWord } from './battle-hud-chrome-image';

/** The three cartridge bakes and the queue state each one is: [name, which header (0 = battle_hud, 1 = battle_hud_sub), queue]. */
const BAKES: [string, 0 | 1, boolean[]][] = [
  ['ctBattleHudBg1Enemy', 0, [false, false, false]],
  ['ctBattleHudBg1Cmd', 0, [true, true, false]],
  ['ctBattleHudBg1Tgt', 1, [false, true, false]],
];

/** The key of (tile word, strip line, x & 7). */
const keyOf = (tile: number, line: number, p: number): number => tile * 512 + line * 8 + p;

/** Lays the bakes over the ROM's tilemap per queue: every pixel a sample of (tile, line, x & 7); returns the table and the sample count. */
const sampleBakes = (rom: Uint8Array, headers: [string, string]): { table: Map<number, number>; n: number } => {
  const table = new Map<number, number>();
  let n = 0;
  for (const [name, which, q] of BAKES) {
    const px = parseBake(headers[which], name);
    const tm = chromeImage(rom, q);
    for (let ry = 0; ry < 48; ry += 1) {
      for (let x = 0; x < 256; x += 1) {
        const tile = tileWord(tm, ry >> 3, x >> 3);
        const key = keyOf(tile, ry, x & 7);
        const value = (px[ry] as number[])[x] as number;
        n += 1;
        const known = table.get(key);
        if (known !== undefined && known !== value) {
          throw new Error(`CONFLICT: ${name} line ${ry} x ${x} tile ${hex(tile, 4)}: ${known} vs ${value}`);
        }
        table.set(key, value);
      }
    }
  }
  return { table, n };
};

/** Every (tile, line) of every queue state must be sampled for all eight x & 7 positions. */
const checkCovered = (rom: Uint8Array, table: Map<number, number>): void => {
  const need = new Set<number>();
  for (let m = 0; m < 8; m += 1) {
    const tm = chromeImage(rom, [(m & 1) === 1, ((m >> 1) & 1) === 1, ((m >> 2) & 1) === 1]);
    for (let ry = 0; ry < 48; ry += 1) for (let c = 0; c < 32; c += 1) need.add(tileWord(tm, ry >> 3, c) * 64 + ry);
  }
  const miss = [...need]
    .sort((a, b) => a - b)
    .filter((k) => Array.from({ length: 8 }, (_, p) => p).some((p) => !table.has(keyOf(k >> 6, k & 63, p))));
  if (miss.length > 0) {
    throw new Error(`UNCOVERED (tile, line): ${miss.slice(0, 12).map((k) => `(${k >> 6}, ${k & 63})`).join(', ')}`);
  }
};

/** tools/gen/battle_hud_chrome.py: the strip's BG1 chrome per tile, from the ROM and the two HUD headers the earlier stages wrote. */
const genBattleHudChrome = (rom: Uint8Array, hud: string, hudSub: string): string => {
  const { table, n } = sampleBakes(rom, [hud, hudSub]);
  checkCovered(rom, table);
  const words = [...new Set([...table.keys()].map((k) => Math.floor(k / 512)))].sort((a, b) => a - b);
  const L = [
    '// The battle HUD strip CHROME, per BG1 tile -- GENERATED by tools/gen/battle_hud_chrome.py (the mechanism, the',
    '// derivation and the checks are in that file and in disasm/notes/battle_hud_command_windows.md).',
    '// ctBattleHudChromePix[t][line][x & 7] = the ctBattleHudBg1Pal index of tile ctBattleHudChromeWord[t] on strip line',
    "// `line` (0..47): the three cartridge bakes laid over the ROM's own $0B40 tilemap for their queue states, " + `${n} samples,`,
    '// 0 conflicts. 0xFF = the tile never sits on that line.',
    '#ifndef CT_BATTLE_HUD_CHROME_H',
    '#define CT_BATTLE_HUD_CHROME_H',
    '#include <stdint.h>',
    `#define CT_BHUD_CHROME_NT ${words.length}`,
    `static const uint16_t ctBattleHudChromeWord[CT_BHUD_CHROME_NT] = { ${words.map((w) => `0x${hex(w, 4)}`).join(', ')} };`,
    'static const uint8_t ctBattleHudChromePix[CT_BHUD_CHROME_NT][48][8] = {',
  ];
  for (const w of words) {
    const rows: string[] = [];
    for (let ry = 0; ry < 48; ry += 1) {
      rows.push(`{${Array.from({ length: 8 }, (_, p) => table.get(keyOf(w, ry, p)) ?? 255).join(',')}}`);
    }
    L.push(`  { /* ${hex(w, 4)} */ ${rows.join(', ')} },`);
  }
  L.push('};', '#endif', '');
  return L.join('\n');
};

export { genBattleHudChrome };

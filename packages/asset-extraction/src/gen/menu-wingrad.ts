/* @layer shared-asset-extraction @kind logic */
import { romRegion } from '../rom/hirom';
import { hex, hexByte } from './c-text';

const BASE = 0x3fbbf2;
const NLIST = 10;
const PAIRS_AT = 0x28771;

const readLists = (rom: Uint8Array): { lists: Uint8Array[]; addrs: number[] } => {
  const lists: Uint8Array[] = [];
  const addrs: number[] = [];
  let off = BASE;
  for (let i = 0; i < NLIST; i += 1) {
    const n = rom[off] as number;
    addrs.push(off + 1 - 0x3f0000);
    lists.push(romRegion(rom, off + 1, off + 1 + n));
    off += 1 + n;
  }
  return { lists, addrs };
};

/** The 16 (CGADSUB, COLDATA) pairs must decode to the +8..-7 ramp the C side assumes. */
const checkPairs = (rom: Uint8Array): void => {
  const pairs = romRegion(rom, PAIRS_AT, PAIRS_AT + 0x20);
  for (let k = 0; k < 16; k += 1) {
    const cgadsub = pairs[k * 2] as number;
    const coldata = pairs[k * 2 + 1] as number;
    if ((coldata & 0xe0) !== 0xe0) throw new Error('COLDATA must select all three channels');
    const got = (coldata & 0x1f) * (cgadsub & 0x80 ? -1 : 1);
    if (got !== 8 - k) throw new Error(`window-gradient pair ${k} decodes to ${got}, want ${8 - k}`);
  }
};

const describeList = (l: Uint8Array): string => {
  const parts: string[] = [];
  for (let j = 0; j < l.length - 1; j += 2) parts.push(`${l[j] === 0 ? 'flat' : 'RAMP'}${l[j + 1]}`);
  return parts.join(' ');
};

const HEADER = [
  '// GENERATED by tools/gen/menu_wingrad.py -- do not edit.',
  '// The menu WINDOW-GRADIENT lists, ROM $FF:BBF2 (length-prefixed, back to back), consumed by',
  '// the HDMA-table generator C2/86DD. See the script header for the full derivation.',
  '#ifndef CT_MENU_WINGRAD_H\n#define CT_MENU_WINGRAD_H\n#include <stdint.h>',
  '// [kind, height] pairs, kind 0 = FLAT band / 1 = 16-step RAMP / 0x80 = end of list.',
  '// Index 0-5 = the RIBBON OPTION (0 Status, 1 Item, 2 Tech, 3 Config, 4 Form, 5 Save); an',
  "// ENTERED screen keeps the option's list (measured: entering never rewrites $7E:9D99).",
  '// 6-9 are the lists that follow; 8 = the SHOP (screen $0C), measured on its open (--hdma bands',
  "// flat 8 / 32 / 112 / 64 / flat 8; $7E:9D99 written with FF/BC53's body by C2:F376).",
  `#define CT_MENU_WINLIST_N ${NLIST}\n#define CT_MENU_WINLIST_SHOP 8`,
  `static const uint8_t ctMenuWinList[${NLIST}][16] = {`,
];

/** tools/gen/menu_wingrad.py: the menu window-gradient lists as src/data/menu_wingrad.h. */
const genMenuWingrad = (rom: Uint8Array): string => {
  const { lists, addrs } = readLists(rom);
  checkPairs(rom);
  const rows = lists.map((l, i) => {
    const body = Array.from(l, hexByte).join(',');
    const pad = ',0x80'.repeat(Math.max(0, 16 - l.length));
    return `  { ${body}${pad} },  // FF/${hex(addrs[i] as number, 4)}  ${describeList(l)}`;
  });
  return `${[...HEADER, ...rows, '};\n#endif'].join('\n')}\n`;
};

export { genMenuWingrad };

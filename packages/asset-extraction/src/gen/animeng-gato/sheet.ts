import { hex } from '../c-text';
import { SHEET_N, WRAM_SIZE } from './sheet.constants';

const wramOf = (state: Uint8Array): Uint8Array => {
  if (state.length === WRAM_SIZE) return state;
  const isCtls = state[0] === 0x43 && state[1] === 0x54 && state[2] === 0x4c && state[3] === 0x53;
  const payload = isCtls ? state.subarray(16) : state;
  return payload.subarray(69, 69 + WRAM_SIZE);
};

const writeSheet = (state: Uint8Array): string => {
  const wram = wramOf(state);
  const sheet = wram.subarray(0x18000, 0x18000 + SHEET_N * 0x20);
  const o: string[] = [
    '// GENERATED by tools/gen/animeng_gato.py -- do not edit.  *** INTERIM FIXTURE ***',
    `// GATO sprite SHEET: WRAM $7F8000 (ptr $1C57[pidx]), tiles 0..0x${hex(SHEET_N - 1, 3)}, 8x8 4bpp (0x20 B each).`,
    '// Captured from gato_noatk.state (front idle) -- the sheet is FIXED across facings (front==left==up,',
    '// verified this session), so ONE dump serves every GATO pose; facings differ only by which E3 cell-words',
    '// gather. The ROM->$7F8000 boot DECOMPRESSOR (keyed by enemy id 0x92) is the standing open (O3/C5); until',
    '// it is derived this baked dump is the sanctioned interim, exactly like ct_charbase.h.',
    '#ifndef CT_ANIMENG_SHEET_GATO_H',
    '#define CT_ANIMENG_SHEET_GATO_H',
    '#include <stdint.h>',
    `#define CT_ANIMENG_SHEET_GATO_N 0x${hex(SHEET_N, 3)}`,
    'static const uint8_t ctAnimengSheetGato[CT_ANIMENG_SHEET_GATO_N][32] = {',
  ];
  for (let t = 0; t < SHEET_N; t += 1) {
    const b = sheet.subarray(t * 0x20, (t + 1) * 0x20);
    o.push(`  {${Array.from(b, (x) => `0x${hex(x, 2)}`).join(',')}},`);
  }
  o.push('};', '#endif', '');
  return o.join('\n');
};

export { writeSheet };

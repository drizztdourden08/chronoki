/* @layer shared-asset-extraction @kind logic */
import { hex } from '../c-hex';
import { hexByte } from '../c-hex-byte';
import { DIGIT_BASE, NDIGIT, DIGIT_W, DIGIT_PAL, FLASH_PAL, MISS_BASE, MISS_NTILE, RISE_DY, HOLD_FRAMES, LIFETIME } from './fx-head.constants';

const tileRow = (vram: Uint8Array, tile: number): string => {
  const o = tile * 32;
  return Array.from({ length: 32 }, (_, i) => hexByte(vram[o + i] as number)).join(',');
};

const headText = (vram: Uint8Array): string => {
  const out: string[] = [];
  const W = (s: string): void => {
    out.push(s);
  };
  W('// AUTO-GENERATED by tools/gen/battle_fx.py -- DO NOT EDIT.\n');
  W('// CT battle ACTION FEEDBACK: the rising DAMAGE-NUMBER popup + the hurt/hit flash palette.\n');
  W('// Dossier: disasm/notes/battle_actionfx.md. Baked byte-exact from the oracle (GATO fight).\n');
  W(`// Digit d -> OBJ tile 0x${hex(DIGIT_BASE, 3)} + d ('0'..'9'), palette ${DIGIT_PAL}, 8x8 (sz=0), prio 3. A digit OBJ\n`);
  W('// pixel at OAM (x,y) lands at oracle fb true-pixel (x, y+8) (verified 73/73 + 79/79 px).\n');
  W('#ifndef CT_BATTLE_FX_H\n#define CT_BATTLE_FX_H\n#include <stdint.h>\n\n');

  W(`#define CT_FX_DIGIT_BASE 0x${hex(DIGIT_BASE, 3)}   // OBJ tile of '0'; digit d -> CT_FX_DIGIT_BASE + d\n`);
  W(`#define CT_FX_DIGIT_W    ${DIGIT_W}       // px between digit columns (right-adjacent 8x8 cells)\n`);
  W(`#define CT_FX_DIGIT_PAL  ${DIGIT_PAL}       // OBJ palette for the digits\n`);
  W(`#define CT_FX_FLASH_PAL  ${FLASH_PAL}       // OBJ palette used for the target's hurt/hit FLASH (all white)\n`);
  W(`#define CT_FX_MISS_BASE  0x${hex(MISS_BASE, 3)}   // "MISS" glyph left OBJ tile (+1 = right); pal0, sz0, prio3 (battle_miss_evade.md)\n`);
  W(`#define CT_FX_MISS_NTILE ${MISS_NTILE}       // "MISS" glyph width in 8x8 OBJ tiles (spawned on a physical to-hit MISS)\n`);
  W(`#define CT_FX_RISE_N     ${RISE_DY.length}       // entries in ctBattleFxRiseDY (birth..rest)\n`);
  W(`#define CT_FX_HOLD       ${HOLD_FRAMES}       // frames held at rest (dy=0) after the rise, then vanish\n`);
  W(`#define CT_FX_LIFETIME   ${LIFETIME}       // total popup lifetime in render frames (rise + hold)\n\n`);

  W('// Digit OBJ 8x8 tiles \'0\'..\'9\' (4bpp SNES planar, 32 B each), verbatim from the in-battle\n');
  W(`// OBJ VRAM (tile 0x${hex(DIGIT_BASE, 3)} = byte 0x${hex(DIGIT_BASE * 32, 4)}, inside the battle-boot OBJ upload 0x3000-0x3C00).\n`);
  W(`static const uint8_t ctBattleFxDigitTile[${NDIGIT}][32] = {\n`);
  for (let d = 0; d < NDIGIT; d += 1) {
    W(`  {${tileRow(vram, DIGIT_BASE + d)}}, // '${d}' (tile 0x${hex(DIGIT_BASE + d, 3)})\n`);
  }
  W('};\n\n');

  W(`// The "MISS" glyph = OBJ 8x8 tiles 0x${hex(MISS_BASE, 3)} (left) + 0x${hex(MISS_BASE + 1, 3)} (right), palette ${DIGIT_PAL}, sz0, prio3. On a\n`);
  W('// physical to-hit MISS the module spawns THIS (C1/E8E2, popup type 5) instead of the damage digits,\n');
  W("// at the target's damage-number anchor (oracle leftX 128 / centerX 136 over GATO, 16px = 2 tiles).\n");
  W('// Verbatim from the in-battle OBJ VRAM (same 0x3000-0x3C00 boot upload as the digit strip); pixel-\n');
  W('// verified 61/61 + 58/58 opaque px, 0 mismatch, vs a forced-miss fb (--verify, evade patched high).\n');
  W(`static const uint8_t ctBattleFxMissTile[${MISS_NTILE}][32] = {\n`);
  for (let k = 0; k < MISS_NTILE; k += 1) {
    W(`  {${tileRow(vram, MISS_BASE + k)}}, // tile 0x${hex(MISS_BASE + k, 3)} ("MISS" ${k === 0 ? 'left' : 'right'})\n`);
  }
  W('};\n\n');
  return out.join('');
};

export { headText };

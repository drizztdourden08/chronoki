/* @layer shared-asset-extraction @kind logic */
import type { ImportContext } from '../pipeline/import-context.type';
import { requireTools } from './ctgen/require-tools';
import { peek } from './ctgen/peek';
import { chunks } from './ctgen/chunks';
import { hx } from './ctgen/hx';
import { BOOT_FRAMES, PAGE2_AFTER, TEXT_BASE, TEXT_END, BG_TABLE, OAM_TABLE, FONT_WORDS } from './seq-credits.constants';

const die = (msg: string): Error => new Error(`gen_seq_credits: REFUSING -- ${msg}`);
const w16 = (buf: Uint8Array, a: number): number => (buf[a] as number) | ((buf[a + 1] as number) << 8);

const walk = (wram: Uint8Array, start: number): number => {
  let a = start;
  for (;;) {
    if (wram[a] === 0xff) return a + 1;
    a += 2;
    while (wram[a]) a += 1;
    a += 1;
  }
};

const checkCapture = (tag: string, wram: Uint8Array, page: number): void => {
  if (wram[0x384] !== 0x61) die(`${tag}: $0384 = ${hx(wram[0x384] as number, 2)}, not $61 (sequence-table entry 1)`);
  if (wram[0x382] !== page) throw die(`${tag}: $0382 = ${wram[0x382]}, expected page ${page}`);
  if (w16(wram, 0x922) !== 0x6be5) {
    throw die(`${tag}: the page timer $7E:6BE5 is not in the task list ($0922 = ${hx(w16(wram, 0x922), 4)})`);
  }
};

const checkFont = (font: Uint8Array, font2: Uint8Array): void => {
  if (!font.every((v, i) => v === font2[i])) {
    throw die(`the font words $0000..$${hx(FONT_WORDS - 1, 3)} differ between page 1 and page 2 -- they are not a boot asset`);
  }
  for (let tile = 0x10; tile < 0x40; tile += 1) {
    if (font.subarray(tile * 32 + 16, tile * 32 + 32).some((v) => v !== 0)) {
      throw die(`OBJ font tile $${hx(tile, 2)} has non-empty planes 2/3 -- $7E:66B0 pads them with zeroes`);
    }
  }
  if (!font.subarray(0, 0x200).some((v) => v !== 0)) throw die('the BG font (VRAM words $0000..$00FF) is empty -- packet $AE did not land');
};

const checkStreams = (wram: Uint8Array, bgp: number[], oamp: number[]): void => {
  for (const p of [...bgp, ...oamp]) {
    if (!(p >= TEXT_BASE && p < TEXT_END)) {
      throw die(`a page pointer ($${hx(p, 4)}) falls outside the text block $${hx(TEXT_BASE, 4)}..$${hx(TEXT_END - 1, 4)}`);
    }
  }
  let cursor = TEXT_BASE;
  for (let i = 0; i < 5; i += 1) {
    if (bgp[i] !== cursor) throw die(`page ${i + 1} BG stream starts at $${hx(bgp[i] as number, 4)}, but the previous stream ended at $${hx(cursor, 4)}`);
    cursor = walk(wram, bgp[i] as number);
    if (oamp[i] !== cursor) throw die(`page ${i + 1} OAM stream starts at $${hx(oamp[i] as number, 4)}, but its BG stream ended at $${hx(cursor, 4)}`);
    cursor = walk(wram, oamp[i] as number);
  }
  if (cursor !== TEXT_END) throw die(`the five pages end at $${hx(cursor, 4)}, not $${hx(TEXT_END, 4)}`);
};

const rows = (vals: number[], per: number, digits: number): string =>
  chunks(vals, per)
    .map((r) => `  ${r.map((v) => `0x${hx(v, digits)},`).join(' ')}`)
    .join('\n');

const render = (font: number[], bgp: number[], oamp: number[], text: number[]): string => {
  const ptrs = (p: number[]): string => p.map((v) => `0x${hx(v, 4)},`).join(' ');
  return [
    '// GENERATED by tools/gen/seq_credits.py -- do not edit.',
    '// Sequence-table ENTRY 1, the staff credits ($7E:6B04). disasm/notes/sequence_table.md.',
    '//',
    `// Only two things here: the FONTS the boot built (VRAM words $0000..$${hx(FONT_WORDS - 1, 3)} -- the BG half`,
    '// is read as 2bpp in mode 0, the OBJ half as 4bpp with zeroed upper planes) and the',
    "// overlay's own TEXT STREAMS. The tilemap, the OAM, the palette and every frame count",
    '// are the machine\'s, and src/title_intro.c runs them.',
    '#ifndef CT_DATA_SEQ_CREDITS_H',
    '#define CT_DATA_SEQ_CREDITS_H',
    '',
    `#define CT_CRED_FONT_WORDS 0x${hx(FONT_WORDS, 3)}`,
    `#define CT_CRED_TEXT_BASE  0x${hx(TEXT_BASE, 4)}`,
    '#define CT_CRED_PAGES      5',
    '',
    `static const unsigned short ctCredFont[${FONT_WORDS}] = {`,
    rows(font, 12, 4),
    '};',
    '',
    "// $7E:6CAC and $7E:6CB6: where each page's BG and OAM stream begins.",
    `static const unsigned short ctCredBgPtr[5]  = { ${ptrs(bgp)} };`,
    `static const unsigned short ctCredOamPtr[5] = { ${ptrs(oamp)} };`,
    '',
    `// $7E:${hx(TEXT_BASE, 4)}..$${hx(TEXT_END - 1, 4)}. A BG record is <vword lo> <vword hi> then a NUL-terminated string;`,
    '// an OAM record is <x> <y> then the string. $FF ends a stream.',
    `static const unsigned char ctCredText[${text.length}] = {`,
    rows(text, 16, 2),
    '};',
    '',
    '#endif',
    '',
  ].join('\n');
};

const genSeqCredits = async (ctx: ImportContext): Promise<string> => {
  const boot = await requireTools(ctx).powerOn({ frames: BOOT_FRAMES, sram: null });
  const p1 = await peek(ctx, boot.state, '0:1', { rule: false });
  const p2 = await peek(ctx, boot.state, `0:${PAGE2_AFTER}`, { rule: false });
  checkCapture('capture A', p1.wram, 1);
  checkCapture('capture B', p2.wram, 2);
  const font = p1.vram.subarray(0, FONT_WORDS * 2);
  checkFont(font, p2.vram.subarray(0, FONT_WORDS * 2));
  const bgp = Array.from({ length: 5 }, (_, i) => w16(p1.wram, BG_TABLE + 2 * i));
  const oamp = Array.from({ length: 5 }, (_, i) => w16(p1.wram, OAM_TABLE + 2 * i));
  checkStreams(p1.wram, bgp, oamp);
  const fontw = Array.from({ length: FONT_WORDS }, (_, i) => w16(font, 2 * i));
  return render(fontw, bgp, oamp, Array.from(p1.wram.subarray(TEXT_BASE, TEXT_END)));
};

export { genSeqCredits };

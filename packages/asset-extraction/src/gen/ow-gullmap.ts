/* @layer shared-asset-extraction @kind logic */
import type { ImportContext } from '../pipeline/import-context.type';
import { requireBytes } from '../pipeline/work-files';
import { peek } from './ctgen/peek';
import { cgramOf } from './ctgen/cgram-of';
import { recipeState } from './ctgen/recipe-state';
import { hx } from './ctgen/hx';
import { decode16 } from './ow-sprite-decode';
import { sprFrames } from './ow-spr-frames';
import { GULL_NAMES } from './ow-gullmap.constants';
import type { Hit } from './ow-gullmap.type';

const sameBytes = (a: Uint8Array, b: Uint8Array): boolean => a.length === b.length && a.every((v, i) => v === b[i]);

const findHits = (vram: Uint8Array, cg: number[], frames: Uint8Array[]): Map<number, Hit[]> => {
  const hits = new Map<number, Hit[]>();
  for (let pal = 0; pal < 8; pal += 1) {
    for (const nm of GULL_NAMES) {
      const dec = decode16(vram, cg, { name: nm, pal });
      frames.forEach((f, k) => {
        if (sameBytes(f, dec)) hits.set(nm, [...(hits.get(nm) ?? []), [pal, k]]);
      });
    }
  }
  return hits;
};

const nameHex = (nm: number): string => hx(nm, 3);

const checkHits = (hits: Map<number, Hit[]>): number => {
  const missing = GULL_NAMES.filter((nm) => !hits.has(nm)).map(nameHex);
  if (missing.length > 0) {
    throw new Error(`ow_gullmap: no exact pixel match for tile(s) ${missing.join(', ')} -- stale atlas, wrong state, or wrong palette`);
  }
  for (const [nm, hs] of hits) {
    if (hs.length !== 1) {
      throw new Error(`ow_gullmap: tile ${nameHex(nm)} matched ${hs.length} (palette, slot) pairs, expected exactly 1: ${JSON.stringify(hs)}`);
    }
  }
  const pals = new Set([...hits.values()].map((h) => (h[0] as Hit)[0]));
  if (pals.size !== 1) throw new Error(`ow_gullmap: tiles matched under different palettes: ${[...pals].join(', ')}`);
  return [...pals][0] as number;
};

const genOwGullmap = async (ctx: ImportContext): Promise<string> => {
  const w0 = await recipeState(ctx, 'ow_nav_w0');
  const spr = await requireBytes(ctx.work, 'saves/ow_gulls.spr');
  const x = await peek(ctx, w0, '0:40', { rule: false });
  const cgBytes = cgramOf(x);
  const cg = Array.from({ length: 256 }, (_, i) => (cgBytes[i * 2] as number) | ((cgBytes[i * 2 + 1] as number) << 8));
  const hits = findHits(x.vram, cg, sprFrames(spr));
  const pal = checkHits(hits);
  const lines = [
    '// ow_gullmap.h - ROM tile name -> captured gull atlas slot, DERIVED BY PIXEL IDENTITY.',
    '// Generated by tools/_gen_owgullmap.py -- DO NOT EDIT BY HAND.',
    '//',
    "// The anim sub-VM's op-4 descriptor names a 9-bit OBJ tile (C2/0D08 word2 bits0-8); the",
    '// captured atlas is indexed by CAPTURE ORDER, which carries no ROM identity. Each tile below',
    "// was decoded from a live overworld state's VRAM with the gull's own palette (attr 0xBA ->",
    `// OBJ palette ${pal}) and matched EXACTLY, byte for byte, against one atlas frame.`,
    '// The generator asserts the match is unique, so a stale atlas fails loudly.',
    '#ifndef CT_OW_GULLMAP_H',
    '#define CT_OW_GULLMAP_H',
    '#include <stdint.h>',
    'typedef struct { uint16_t name; uint8_t slot; } CtOwGullFrame;',
    'static const CtOwGullFrame ctOwGullMap[] = {',
    ...GULL_NAMES.map((nm) => `  { 0x${nameHex(nm)}, ${((hits.get(nm) as Hit[])[0] as Hit)[1]} },`),
    '};',
    `#define CT_OWGULLMAP_N ${GULL_NAMES.length}`,
    '#endif',
  ];
  return `${lines.join('\n')}\n`;
};

export { genOwGullmap };

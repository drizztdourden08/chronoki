import { romRegion } from '../rom/hirom';
import { hexByte } from './c-text';

const RETURN_HEAD = [0xe3, 0x00, 0x89, 0x40, 0x0d, 0x00, 0x0e, 0x02, 0xae, 0x95, 0x00, 0x0e, 0x00, 0x71, 0xff];
const RETURN_BARRIER = [0x12, 0xff, 0x03, 0x04, 0x04];
const RETURN_TAIL = [0xe3, 0x01, 0x00, 0x11, 0x09];

const startsWith = (data: Uint8Array, at: number, want: number[]): boolean => want.every((b, i) => data[at + i] === b);

const emit = (name: string, data: Uint8Array): string =>
  `static const uint8_t ${name}[${data.length}] = {\n  ${Array.from(data, hexByte).join(', ')}\n};\n`;

const COMMENT = [
  '// GENERATED by tools/gen/ct_regroup.py -- do not edit. The ROM battle-RETURN regroup script',
  '// templates (disasm/notes/battle_forest_return.md AD.3a): C0/5CEC copies these into $7F3700+.',
  '// The post-victory resume (C0/0330 -> C0/5B1F) VM-CALLs ctRegroupReturn on each FOLLOWER PC;',
  '// its E3/89/0D/0E/AE/95/71/12/11/00 ops all exist in ct_vm.c. loc[0xFF] (= the walk-arrival',
  '// barrier) is seeded 3-nFollowers so only the last arriver passes the `E3 01` control-restore.',
  '//   RETURN block: E3 00|89 40|0D 00|0E 02|AE|95 00|0E 00|71 FF|12 FF 03 04 04|E3 01|00|11 09',
];

/** tools/gen/ct_regroup.py: the battle-return regroup script templates (C0/5D37, 5D50, 5D68) as src/data/ct_regroup.h. */
const genCtRegroup = (rom: Uint8Array): string => {
  const ret = romRegion(rom, 0x5d37, 0x5d37 + 0x20);
  const d9 = romRegion(rom, 0x5d50, 0x5d50 + 0x20);
  const tail = romRegion(rom, 0x5d68, 0x5d68 + 6);
  if (!startsWith(ret, 0, RETURN_HEAD)) throw new Error('RETURN block head mismatch -- ROM changed?');
  if (!startsWith(ret, 15, RETURN_BARRIER)) throw new Error('RETURN block barrier-IF mismatch');
  if (!startsWith(ret, 20, RETURN_TAIL)) throw new Error('RETURN block tail mismatch');
  return [
    ...COMMENT.map((l) => `${l}\n`),
    '#ifndef CT_REGROUP_H\n#define CT_REGROUP_H\n#include <stdint.h>\n',
    emit('ctRegroupReturn', ret),
    emit('ctRegroupD9', d9),
    emit('ctRegroupTail', tail),
    '#endif\n',
  ].join('');
};

export { genCtRegroup };

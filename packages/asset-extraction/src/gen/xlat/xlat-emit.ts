/* @layer shared-asset-extraction @kind logic */
import { fmt, TABLE } from './disasm';
import type { Site, Sites } from './xlat-site.type';
import { successors } from './xlat-static';

const hx = (value: number, digits: number): string => value.toString(16).toUpperCase().padStart(digits, '0');

const ramCode = (adr: number): boolean => {
  const k = adr >> 16;
  const p = adr & 0xffff;
  return k === 0x7e || k === 0x7f || ((k < 0x40 || (k >= 0x80 && k < 0xc0)) && p < 0x2000);
};

const comment = (adr: number, s: Site): string => {
  const [mnem, mode] = TABLE[s.op] as readonly [string, string];
  const [plain, tgt, reg] = fmt(mnem, mode, adr >> 16, adr & 0xffff, s.bytes.slice(1));
  const text = (mode === 'rel' || mode === 'rell') && tgt !== null ? `${mnem} ->${hx(tgt & 0xffff, 4)}` : plain;
  return text + (reg ? `  ; ${reg}` : '') + (s.traced ? '' : '  [static]') + (s.smc ? '  [SMC operand]' : '');
};

const siteLine = (adr: number, s: Site, sites: Sites, stops: Set<number>): string => {
  const pad = [...s.bytes];
  while (pad.length < 4) pad.push(0);
  const ex = ramCode(adr) && !s.smc
    ? `X_EXEC_RAM(0x${hx(s.op, 2)}, ${s.len}, 0x${hx(pad[1] as number, 2)}, 0x${hx(pad[2] as number, 2)}, 0x${hx(pad[3] as number, 2)});`
    : `X_EXEC(0x${hx(s.op, 2)});`;
  const { targets, falls, next } = successors(adr, s);
  let flow = '';
  const t = targets[0];
  if (t !== undefined) {
    if (sites.has(t)) flow = ` if (X_PC == 0x${hx(t, 6)}) goto L_${hx(t, 6)};`;
    else if (stops.has(t)) flow = ` if (X_PC == 0x${hx(t, 6)}) return CT_XLAT_EXIT;`;
  }
  if (!falls) flow += ' goto dispatch;';
  else if (s.op === 0x54 || s.op === 0x44) flow += ` if (X_PC == 0x${hx(adr, 6)}) goto L_${hx(adr, 6)};`;
  else if (!sites.has(next)) flow += ' goto dispatch;';
  return `L_${hx(adr, 6)}: X_BOUNDARY(0x${hx(adr, 6)}); ${ex}${flow}  // ${comment(adr, s)}`;
};

const emitProgram = (name: string, sites: Sites, stops: Set<number>, staticCount: number, tracedCount: number): string => {
  const smcCount = [...sites.values()].filter((s) => s.smc).length;
  const order = [...sites.keys()].sort((a, b) => a - b);
  const exits = [...stops].sort((a, b) => a - b);
  const out: string[] = [
    "// GENERATED by tools/gen/xlat.py -- do not edit. Regenerate from the oracle trace; see the tool's docstring.",
    `// ${sites.size} instructions (${tracedCount} executed on the oracle, ${staticCount} decoded statically), ${smcCount} with a self-modified operand.`,
    "// Each label is one instruction at its K:PPPP. The program is here; the semantics and the clock are cpu.c's.",
    '#include "../seq_xlat.h"',
    '',
    `int CtXlat_${name}(CtXlat* x) {`,
    '  Cpu* c = x->cpu;',
    'dispatch:',
    '  switch (((uint32_t)c->k << 16) | c->pc) {',
    ...order.map((adr) => `    case 0x${hx(adr, 6)}: goto L_${hx(adr, 6)};`),
    ...exits.map((adr) => `    case 0x${hx(adr, 6)}: return CT_XLAT_EXIT;`),
    '    default: { int r_ = ctXlatInterp(x, 1); if (r_) return r_; goto dispatch; }',
    '  }',
    ...order.map((adr) => siteLine(adr, sites.get(adr) as Site, sites, stops)),
    '}',
    '',
  ];
  return out.join('\n');
};

export { emitProgram };

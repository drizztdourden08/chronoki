/* @layer shared-asset-extraction @kind logic */
import { romRegion } from '../rom/hirom';
import { cArray } from './c-array';
import { hex } from './c-hex';
import { TABLE_BYTES, TABLES } from './battle-trig.constants';

const emitArray = (rom: Uint8Array, name: string, offset: number, note: string): string =>
  [
    `// ${note} -- ${TABLE_BYTES} bytes copied verbatim from ROM file 0x${hex(offset, 5)}.`,
    ...cArray('unsigned char', name, romRegion(rom, offset, offset + TABLE_BYTES)),
  ].join('\n');

const genBattleTrig = (rom: Uint8Array): string => {
  const parts = [
    '// AUTO-GENERATED by tools/gen/battle_trig.py -- DO NOT EDIT. See that file for the derivation.',
    '// Battle enemy-movement trig tables (disasm/notes/battle_enemy_move_target.md).',
    '#ifndef CT_BATTLE_TRIG_H',
    '#define CT_BATTLE_TRIG_H',
    '',
  ];
  for (const [name, offset, note] of TABLES) parts.push(emitArray(rom, name, offset, note), '');
  parts.push('#endif');
  return `${parts.join('\n')}\n`;
};

export { genBattleTrig };

/* @layer shared-asset-extraction @kind logic */
import { romRegion } from '../rom/hirom';
import { hexByte } from './c-text';

const N = 22;
const TABLES: [name: string, offset: number, note: string][] = [
  ['ctCollSlopeBF5', 0x9bf5, 'C0/9BF5: bit 7 = negate X after the shift; bits 0-6 = the LSR count'],
  ['ctCollSlopeC0B', 0x9c0b, 'C0/9C0B: the constant added after the shift'],
  ['ctCollSlopeC21', 0x9c21, 'C0/9C21: the EOR sign (00 keep / FF invert)'],
];

/** tools/gen/coll_slope.py: the field collision's slope tables (C0/9AD3) as src/data/coll_slope.h. */
const genCollSlope = (rom: Uint8Array): string => {
  const lines = [
    "// GENERATED by tools/gen/coll_slope.py -- do not edit. The field collision's slope tables (C0/9AD3).",
    '#ifndef CT_COLL_SLOPE_H',
    '#define CT_COLL_SLOPE_H',
    '#include <stdint.h>',
    `#define CT_COLL_SLOPE_N ${N}`,
  ];
  for (const [name, offset, note] of TABLES) {
    lines.push(`// ${note}`);
    lines.push(`static const uint8_t ${name}[CT_COLL_SLOPE_N] = {`);
    lines.push(`  ${Array.from(romRegion(rom, offset, offset + N), hexByte).join(',')} };`);
  }
  lines.push('#endif');
  return `${lines.join('\n')}\n`;
};

export { genCollSlope };

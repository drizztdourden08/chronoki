/* @layer shared-asset-extraction @kind logic */
import type { ImportContext } from '../pipeline/import-context.type';
import { readText } from '../pipeline/work-files';
import type { PeekDump } from '../oracle/peek.type';
import { peekOracle, recipeState } from '../oracle/peek-access';
import { OVERSCAN, STRIP_H, STRIP_Y0 } from './battle-hud-strip';
import { rgbOfFb } from './shared/rgb-of-fb';
import type { GenFiles } from './oracle-gen-stage';

const CAPTURES: [name: string, script: string][] = [
  ['ctBattleHudBg1SubTech', '0:600,20:2,0:20,100:2,0:60'],
  ['ctBattleHudBg1SubItem', '0:600,20:2,0:12,20:2,0:20,100:2,0:60'],
  ['ctBattleHudBg1Tgt', '0:600,100:2,0:20,100:2,0:200'],
];

const HEAD = [
  '// Battle Tech/Item SUBMENU chrome -- CAPTURED from the oracle, BG1 only.',
  '// GENERATED by tools/gen/battle_hud_sub.py -- see that file for the capture recipe.',
  '// The strip chrome is 100% BG1 (battle_hud_render.md Q2), so a PEEK_ISOBG=0 capture of the',
  '// open submenu IS the chrome: no text, no OBJ, nothing to subtract. Indices into',
  '// ctBattleHudBg1Pal -- both phases use only colours it already has, so the palette is untouched.',
  '// ⭐ WHAT THIS CORRECTED: the previous version was ASSEMBLED from the COMMAND phase\'s pixels,',
  '// with the window structure read off captures believed to be hires/2x ("the left window\'s',
  '// right frame at real x~124 = dump 248-249 dark dip"). The Tech submenu\'s junction is at',
  '// columns 172/175 -- TWO dark columns -- not 124/127/128/131; the assembled version put a',
  '// whole extra frame pair 48 px too far left. Item is one unified window on both.',
  '#ifndef CT_BATTLE_HUD_SUB_H',
  '#define CT_BATTLE_HUD_SUB_H',
  '#include <stdint.h>',
  '// ctBattleHudBg1Tgt: the TARGET-SELECT layout -- the command boxes with box0 4 px',
  '// narrower (dividers at 48/51 against the command bake\'s 52/55, the rest identical).',
];

/** The palette of battle_hud.h (the generated header, read back from the workdir). */
const palette = async (ctx: ImportContext): Promise<string[]> => {
  const s = await readText(ctx.work, 'src/data/battle_hud.h');
  if (s === null) throw new Error('src/data/battle_hud.h is missing: the stage that makes it did not run');
  const i = s.indexOf('ctBattleHudBg1Pal[62][3]');
  if (i < 0) throw new Error('substring not found');
  const j = s.indexOf('};', i);
  return [...s.slice(i, j).matchAll(/\{(\d+),(\d+),(\d+)\}/g)].map((m) => `${Number(m[1])},${Number(m[2])},${Number(m[3])}`);
};

const bake = (dump: PeekDump, pal: string[]): number[][] => {
  const d = rgbOfFb(dump.fb);
  const rows: number[][] = [];
  for (let ry = 0; ry < STRIP_H; ry += 1) {
    const y = STRIP_Y0 + ry + OVERSCAN;
    const row: number[] = [];
    for (let x = 0; x < 256; x += 1) {
      const k = (y * 256 + x) * 3;
      const c = `${d[k]},${d[k + 1]},${d[k + 2]}`;
      const at = pal.indexOf(c);
      if (at < 0) throw new Error(`colour (${c}) at (${x},${ry}) is not in ctBattleHudBg1Pal`);
      row.push(at);
    }
    rows.push(row);
  }
  return rows;
};

/** tools/gen/battle_hud_sub.py: the battle Tech/Item/target-select submenu chrome as src/data/battle_hud_sub.h. */
const genBattleHudSub = async (ctx: ImportContext): Promise<GenFiles> => {
  const oracle = peekOracle(ctx);
  const state = await recipeState(ctx, 'gato_inbattle');
  const pal = await palette(ctx);
  const lines = [...HEAD];
  for (const [name, script] of CAPTURES) {
    const rows = bake(await oracle.peek({ state, script, env: { PEEK_ISOBG: '0' } }), pal);
    lines.push(`static const uint8_t ${name}[${STRIP_H}][256] = {`);
    for (const r of rows) lines.push(`  {${r.join(',')}},`);
    lines.push('};');
  }
  lines.push('#endif');
  return { 'battle_hud_sub.h': `${lines.join('\n')}\n` };
};

export { genBattleHudSub };

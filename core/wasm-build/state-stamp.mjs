// The stamp a build writes into every save state (reconnect/ck_state_schema.c), generated into out/gen/ck_state_stamp.h:
//  * the Belthasar pin commit (core/belthasar.pin.json);
//  * ChronoKi's core version: bump CORE_VERSION when the core's own save/load behaviour changes. It is informational: it
//    decides nothing about which states load;
//  * one schema id per section (I-77): a hash over what fixes that section's layout. A state lists the ids of the sections
//    it carries (`sections=CORE:<id>,SCEN:<id>,...`) and loads when each one equals this build's id, so a change to one
//    section refuses only the states that carry it (a field state never carries WRLD or MENU), and a version bump with no
//    layout change refuses nothing. CORE: the sizes of the WRAM and SRAM images. SCEN: the engine's own scene state version
//    (CT_STATE_VERSION in the pinned ct_vm.c). HOST, WRLD, MENU: their field lists (ck_host_fields.h; the three world lists;
//    the three menu lists and the stash size), so adding, removing or retyping a field changes that section's id;
//  * the whole-state schema: a hash over all the section ids, the build's identity (the app's capture drift check);
//  * the past layouts (state-past.mjs): states from cores before per-section ids, which stamped only the whole-state hash.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { hostFieldList } from './host-fields.mjs';
import { menuFieldListText } from './menu-fields.mjs';
import { PAST_LAYOUTS } from './state-past.mjs';
import { worldFieldListText } from './world-fields.mjs';

const CORE_VERSION = '0.4.1';
const CONTAINER_VERSION = 2;
const WRAM_BYTES = 0x20000;
const SRAM_BYTES = 0x2000;
const MENU_STASH_BYTES = 0x60F8;

const sceneStateVersion = (belthasar) => {
  const text = readFileSync(join(belthasar, 'src', 'ct_vm.c'), 'utf8');
  const m = /#define\s+CT_STATE_VERSION\s+(\d+)u/.exec(text);
  if (!m) throw new Error('ct_vm.c: CT_STATE_VERSION not found; the scene state format moved upstream, update state-stamp.mjs');
  return m[1];
};

const hash = (text, n) => createHash('sha256').update(text).digest('hex').slice(0, n);

// [container tag, stamp name, the text that fixes the layout], in the order ck_state.c writes them
const sectionTexts = (belthasar, root) => {
  const host = hostFieldList(root).map((h) => `${h.name}:${h.type}${h.dims}`).join(',');
  return [
    ['CORE', 'CORE', `CORE.1;wram=${WRAM_BYTES};sram=${SRAM_BYTES}`],
    ['SCEN', 'SCEN', `SCEN.1;engine=${sceneStateVersion(belthasar)}`],
    ['HOST', 'HOST', `HOST.1;${host}`],
    ['WRLD', 'WRLD', `WRLD.1;${worldFieldListText(root)}`],
    ['MENU', 'MENU', `MENU.1;${menuFieldListText(root)};stash=${MENU_STASH_BYTES}`],
    ['MPIC', 'MPIC', 'MPIC.1;rle3'],
    ['APU ', 'APU', 'APU.1'],
    ['APUH', 'APUH', 'APUH.1'],
  ];
};

const idList = (sections) => Object.entries(sections).map(([name, id]) => `${name}:${id}`).join(',');

const writeStampHeader = (genDir, belthasar, root) => {
  const pin = JSON.parse(readFileSync(join(root, 'core', 'belthasar.pin.json'), 'utf8'));
  if (!pin.commit) throw new Error('core/belthasar.pin.json has no commit');
  const ids = sectionTexts(belthasar, root).map(([tag, name, text]) => ({ tag, name, id: hash(text, 8) }));
  const line = idList(Object.fromEntries(ids.map((s) => [s.name, s.id])));
  const schema = hash(`CKST.${CONTAINER_VERSION};${line}`, 16);
  const table = ids.map((s) => `{ "${s.tag}", "${s.name}", "${s.id}" }`).join(', \\\n  ');
  const past = PAST_LAYOUTS.map((p) => `{ "${p.schema}", "${idList(p.sections)}" }`).join(', \\\n  ');
  writeFileSync(join(genDir, 'ck_state_stamp.h'), `/* generated by core/wasm-build/state-stamp.mjs */
#ifndef CK_STATE_STAMP_H
#define CK_STATE_STAMP_H
#define CK_STATE_PIN_COMMIT "${pin.commit}"
#define CK_STATE_CORE_VERSION "${CORE_VERSION}"
#define CK_STATE_SCHEMA "${schema}"
#define CK_STATE_SECTION_COUNT ${ids.length}
#define CK_STATE_SECTION_IDS { \\
  ${table} }
#define CK_STATE_PAST_COUNT ${PAST_LAYOUTS.length}
#define CK_STATE_PAST { \\
  ${past} }
#endif
`);
};

export { writeStampHeader }

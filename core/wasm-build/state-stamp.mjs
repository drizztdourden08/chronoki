// The stamp a build writes into every save state (reconnect/ck_state.c), generated into out/gen/ck_state_stamp.h:
//  * the Belthasar pin commit (core/belthasar.pin.json);
//  * ChronoKi's core version: bump CORE_VERSION when the core's own save/load behaviour changes;
//  * the schema hash: a hash over the container's section table, the sizes of the core block and the engine's own scene
//    state version (CT_STATE_VERSION in the pinned ct_vm.c), so a state whose layout this build cannot read is refused with
//    a reason instead of half-loaded. The HOST section's field list (core/reconnect/ck_host_fields.h: name, type, size
//    expression) is part of the hashed text, so adding, removing or retyping a host field changes the schema.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { hostFieldList } from './host-fields.mjs';

const CORE_VERSION = '0.2.1';
const CONTAINER_VERSION = 2;
const SECTIONS = { STMP: 1, CORE: 1, HOST: 1, APU: 1, APUH: 1 };
const WRAM_BYTES = 0x20000;
const SRAM_BYTES = 0x2000;

const sceneStateVersion = (belthasar) => {
  const text = readFileSync(join(belthasar, 'src', 'ct_vm.c'), 'utf8');
  const m = /#define\s+CT_STATE_VERSION\s+(\d+)u/.exec(text);
  if (!m) throw new Error('ct_vm.c: CT_STATE_VERSION not found; the scene state format moved upstream, update state-stamp.mjs');
  return m[1];
};

const schemaText = (belthasar, root) => {
  const sections = Object.entries({ ...SECTIONS, SCEN: sceneStateVersion(belthasar) }).map(([tag, v]) => `${tag}.${v}`);
  const host = hostFieldList(root).map((h) => `${h.name}:${h.type}${h.dims}`).join(',');
  return `CKST.${CONTAINER_VERSION};${sections.join(',')};wram=${WRAM_BYTES};sram=${SRAM_BYTES};host=${host}`;
};

const writeStampHeader = (genDir, belthasar, root) => {
  const pin = JSON.parse(readFileSync(join(root, 'core', 'belthasar.pin.json'), 'utf8'));
  if (!pin.commit) throw new Error('core/belthasar.pin.json has no commit');
  const schema = createHash('sha256').update(schemaText(belthasar, root)).digest('hex').slice(0, 16);
  writeFileSync(join(genDir, 'ck_state_stamp.h'), `/* generated by core/wasm-build/state-stamp.mjs */
#ifndef CK_STATE_STAMP_H
#define CK_STATE_STAMP_H
#define CK_STATE_PIN_COMMIT "${pin.commit}"
#define CK_STATE_CORE_VERSION "${CORE_VERSION}"
#define CK_STATE_SCHEMA "${schema}"
#endif
`);
};

export { writeStampHeader }

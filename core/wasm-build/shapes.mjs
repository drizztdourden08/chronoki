// Generated-at-build files, written under out/gen/ (never committed, never into the git-ignored import).
//  * the oracle module: main.c includes "data/animeng_sheet_gato.h" unconditionally (a check datum the data-free import
//    does not carry). A zeroed definition of the same shape stands in; --sheetcheck is not part of what the oracle is for.
//  * the game module's table storage and pack loader for wasm32 (docs/p3-findings.md, unknown 2): the imported ones are
//    generated for a 64-bit pointer model. tables_storage.c is taken from out/tables32/ when a 32-bit one was generated
//    there (tools/gen/pack_tables.py headers with PTR_SIZE = 4); otherwise the imported one is used with its
//    compile-time CT_TBL_CHECK size asserts removed, so the module links and the pack loader names the first mismatch.
//    datapack.c gets one exact-match text patch (u32 pointer slots when sizeof(void*) == 4) that fails the build loudly
//    if upstream's line changes.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { belthasar, root } from './sources.mjs';
import { writeStampHeader } from './state-stamp.mjs';
import { writeStatePatches } from './state-patches.mjs';

const sheetShape = () => {
  const src = readFileSync(join(belthasar, 'src', 'tables', 'animeng_sheet_gato.h'), 'utf8');
  const n = /#define\s+CT_ANIMENG_SHEET_GATO_N\s+(\S+)/.exec(src);
  if (!n) throw new Error('tables/animeng_sheet_gato.h: CT_ANIMENG_SHEET_GATO_N not found');
  return `/* generated by core/wasm-build/shapes.mjs: zeroed, shape only */
#ifndef CK_SHAPE_ANIMENG_SHEET_GATO_H
#define CK_SHAPE_ANIMENG_SHEET_GATO_H
#include <stdint.h>
#define CT_ANIMENG_SHEET_GATO_N ${n[1]}
static const uint8_t ctAnimengSheetGato[CT_ANIMENG_SHEET_GATO_N][32];
#endif
`;
};

const PTR_LINE = 'uint64_t so = rd64(src + at);';
const PTR_PATCH =
  'uint64_t so = sizeof(void*) == 4 ? (rd32(src + at) == 0xFFFFFFFFu ? UINT64_MAX : (uint64_t)rd32(src + at)) : rd64(src + at);';

const patchedDatapack = () => {
  const text = readFileSync(join(belthasar, 'src', 'datapack.c'), 'utf8');
  if (!text.includes(PTR_LINE)) throw new Error('datapack.c: the pointer-slot read changed upstream; update shapes.mjs');
  return text.replace(PTR_LINE, PTR_PATCH);
};

const tableStorage = (outDir) => {
  const own = join(outDir, 'tables32', 'tables_storage.c');
  const text = readFileSync(existsSync(own) ? own : join(belthasar, 'src', 'tables', 'tables_storage.c'), 'utf8');
  const noChecks = existsSync(own) ? text : text.replace(/^CT_TBL_CHECK\(.*\);\s*$/gm, '');
  // src/tables/X.h can share its name with an engine header in src/ (title_intro.h): name the tables' ones by path
  const fixed = noChecks
    .replace('#include "../datapack.h"', '#include "datapack.h"')
    .replace(/^#include "([A-Za-z0-9_]+\.h)"/gm, (line, h) =>
      existsSync(join(belthasar, 'src', 'tables', h)) ? `#include "tables/${h}"` : line);
  return { text: fixed, is32: existsSync(own) };
};

// returns { dir, gameFiles, state: { files, replaced }, tables32 }; state is the game module's patched engine files (state-patches.mjs)
const writeShapes = (outDir) => {
  const gen = join(outDir, 'gen');
  mkdirSync(join(gen, 'data'), { recursive: true });
  writeFileSync(join(gen, 'data', 'animeng_sheet_gato.h'), sheetShape());
  writeFileSync(join(gen, 'datapack.c'), patchedDatapack());
  const ts = tableStorage(outDir);
  writeFileSync(join(gen, 'tables_storage.c'), ts.text);
  writeStampHeader(gen, belthasar, root);
  const state = writeStatePatches(gen, belthasar, root);
  return { dir: gen, gameFiles: [join(gen, 'datapack.c'), join(gen, 'tables_storage.c')], state, tables32: ts.is32 };
};

export { writeShapes }
